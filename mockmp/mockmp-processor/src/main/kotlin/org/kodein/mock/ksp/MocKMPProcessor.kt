        /**
         * Resolves how to initialize a value of [type], as a KotlinPoet `(format, args)` pair
         * suitable for `addStatement("... $template ...", ..., *args)`:
         *  1. a call to the user's `@FakeProvider` function, if one was registered for [type] —
         *     checked first so it can override any of the cases below, exactly the same way a
         *     provider for a non-builtin type already takes priority over generating a `fakeXxx()`;
         *  2. `T::class`, if [type] (after unwrapping any type alias) is `KClass<T>`/`Class<T>` — one
         *     of three [builtins] entries whose value isn't context-free, so it can't be read off the
         *     map like every other one below; a star-projected or otherwise unresolvable `T` falls
         *     back to `Any::class`, exactly as the map entry itself does for callers with no [type]
         *     to inspect ([generatePlaceholderAccessor]);
         *  3. `MutableStateFlow(<faked T>)`, if [type] is `StateFlow<T>`/`MutableStateFlow<T>` — the
         *     other two such entries: recursing through [fakeValueOf] is what makes a `StateFlow<Foo>`
         *     hold a nested fake, `StateFlow<Foo?>` hold `null`, and so on, the same as any other
         *     faked value of type `T`;
         *  4. a [builtins] literal or factory call, if [type] is one;
         *  5. otherwise, a call to the generated `fakeXxx()` function for [type].
         *
         * Any file backing a case-1 provider is added to [filesDeps] so the generated file
         * correctly depends on it.
         *
         * NOTE: this unifies what used to be two separately-inlined copies of this resolution (one
         * for constructor parameters, one for `@Fake` properties). The property-injection call site
         * ([addFakeInjection]) did not previously unwrap type aliases nor redirect stdlib packages
         * through [fakePackageName] — both are applied uniformly now; the difference is unreachable
         * for any type already covered by [builtins], which is the only stdlib case exercised today.
         */
        private fun fakeInitializerOf(type: KSType, filesDeps: MutableSet<KSFile>): Pair<String, List<Any>> {
            val resolvedType = type.unwrapAliases()
            val decl = resolvedType.declaration
            val qualifiedName = decl.qualifiedName!!.asString()
            if (resolvedType in providedFakes) {
                val f = providedFakes[resolvedType]!!
                f.containingFile?.let { filesDeps += it }
                return "%M()" to listOf(MemberName(f.packageName.asString(), f.simpleName.asString()))
            }
            if (qualifiedName == "kotlin.reflect.KClass" || qualifiedName == "java.lang.Class") {
                val argClassName = (resolvedType.arguments.firstOrNull()?.type?.resolve()?.declaration as? KSClassDeclaration)
                    ?.toClassName()
                    ?: ClassName("kotlin", "Any")
                // `String::class` is a KClass<String>; `java.lang.Class<String>` needs the `.java`
                // conversion property on top of it.
                val template = if (qualifiedName == "java.lang.Class") "%T::class.java" else "%T::class"
                return template to listOf(argClassName)
            }
            if (qualifiedName == "kotlinx.coroutines.flow.StateFlow" || qualifiedName == "kotlinx.coroutines.flow.MutableStateFlow") {
                val (innerTemplate, innerArgs) = fakeValueOf(resolvedType.arguments.first().type!!.resolve(), filesDeps)
                return "%M($innerTemplate)" to (listOf(MemberName("kotlinx.coroutines.flow", "MutableStateFlow")) + innerArgs)
            }
            val builtIn = builtins[qualifiedName]
            return when {
                builtIn != null -> builtIn.template to builtIn.args
                else -> "%M()" to listOf(MemberName(decl.fakePackageName(), "fake${resolvedType.toFunName()}"))
            }
        }

        /**
         * Reports that [vCls] cannot be faked because [reason]. An *implicit* target
         * ([ToProcess.implicit]) gets a `return error("...")` stub appended to [gFun] so the KSP
         * round still succeeds — the error only surfaces if that function is ever actually invoked,
         * which should never happen for a discarded `isAny()`-style placeholder. An explicit target
         * fails fast, aborting the round. Either way the message carries [ToProcess.path] — the
         * requirement chain recorded when [process] was registered — since a type only reaches
         * generation, and only fails here, because something else needed it.
         */
        private fun reportUnfakeable(gFun: FunSpec.Builder, vCls: KSClassDeclaration, reason: String, process: ToProcess) {
            val message = unfakeableMessage(vCls.displayName(), reason, process.path)
            if (process.implicit) gFun.addStatement("return error(%S)", message)
            else error(vCls, message)
        }

        /**
         * Resolves one `(format, args)` pair per non-defaulted parameter of constructor [vCstr] of
         * class [vCls] — `null` for nullable parameters, [fakeInitializerOf] otherwise (a builtin
         * placeholder, a `@FakeProvider`, or a nested `fakeXxx()` call; a no-op lambda when the
         * parameter is itself a function type — with an empty body, and no format arg at all, when
         * that lambda's return type is `Unit`, to avoid a "redundant Unit" warning in generated code).
         * Type parameters of [vCls] are substituted using [vType]'s own type arguments, at any depth
         * (see [substituteTypeParameters]) — the very substitution [constructorParamTypeToFake] used
         * to decide which nested `fakeXxx()` functions to generate, so the two must agree. Shared by
         * fake-class generation ([addFakeClassConstructorCall]) and abstract-class mock generation
         * ([addSuperclassConstructorArgs]).
         */
        private fun resolveConstructorArgs(vCls: KSClassDeclaration, vCstr: KSFunctionDeclaration, vType: KSType, filesDeps: MutableSet<KSFile>): List<Pair<String, List<Any>>> {
            val args = ArrayList<Pair<String, List<Any>>>()
            vCstr.parameters.forEach { vParam ->
                if (!vParam.hasDefault) {
                    val vParamType = substituteTypeParameters(vParam.type.resolve(), vCls, vType)
                        ?: error(vParam, "Could not resolve generic parameter $vParam of ${vCls.qualifiedName?.asString()}")
                    val (template, values) = fakeValueOf(vParamType, filesDeps)
                    args.add("${vParam.name!!.asString()} = $template" to values)
                }
            }
            return args
        }

        /**
         * A faked *value* of [type], as a KotlinPoet `(format, args)` pair: `null` for a nullable
         * type, a no-op lambda for a function type (with an empty body, and no format arg at all,
         * when its return type is `Unit`, to avoid a "redundant Unit" warning in generated code),
         * and [fakeInitializerOf] — a builtin placeholder, a `@FakeProvider`, or a nested `fakeXxx()`
         * call — otherwise.
         *
         * The single source of every faked value: constructor arguments ([resolveConstructorArgs]),
         * property initializers and function bodies of a generated implementation
         * ([addFakeImplementation]) alike. [valueTypeToFake] decides, from the same [type], whether a
         * `fakeXxx()` function has to be generated for the call this emits.
         */
        private fun fakeValueOf(type: KSType, filesDeps: MutableSet<KSFile>): Pair<String, List<Any>> = when {
            type.nullability != Nullability.NOT_NULL -> "%L" to listOf("null")
            type.isAnyFunctionType -> {
                val vLambdaParams = "_, ".repeat(type.arguments.size - 1)
                val vReturnType = type.arguments.last().type!!.resolve()
                if (vReturnType.isUnit()) {
                    "{ $vLambdaParams-> }" to emptyList()
                } else {
                    val (template, values) = fakeInitializerOf(vReturnType, filesDeps)
                    "{ $vLambdaParams-> $template }" to values
                }
            }
            else -> fakeInitializerOf(type, filesDeps)
        }

        /**
         * Appends `return Xxx(param = ...)` to [gFun] using [resolveConstructorArgs] — or, for an
         * *implicit* target with no public constructor, [reportUnfakeable] instead of aborting
         * the KSP round.
         */
        private fun addFakeClassConstructorCall(gFun: FunSpec.Builder, vCls: KSClassDeclaration, vType: KSType, filesDeps: MutableSet<KSFile>, process: ToProcess) {
            val vCstr = vCls.firstPublicConstructor()
            if (vCstr == null) {
                reportUnfakeable(gFun, vCls, "it has no public constructor", process)
                return
            }
            val args = resolveConstructorArgs(vCls, vCstr, vType, filesDeps)
            gFun.addStatement("return %T(${args.joinToString { it.first }})", *(listOf(vCls.toClassName()) + args.flatMap { it.second }).toTypedArray())
        }

        /**
         * The faked override of one abstract property of an implemented interface or abstract class,
         * e.g. for `val bar: String`, mutable `var baz: Data`, and `val dir: SomeDirection`:
         *
         * ```
         * override val bar: String = ""
         * override var baz: Data = fakeData()
         * override val dir: SomeDirection by LazyFake { fakeSomeDirection() }
         * ```
         *
         * [vPropType] is the property's type *as a member of* the implemented instantiation, so a
         * `val content: T` of `GenItf<String>` is faked as a `String`.
         *
         * A property whose value is a nested `fakeXxx()`/`@FakeProvider` call ([KSType.needsLazyFake])
         * is deferred through [LazyFake] rather than built eagerly: an eager `override val parent:
         * Node = fakeNode()` would recurse forever faking a self-referential type
         * (`interface Node { val parent: Node }`), where building `parent` requires building
         * `parent.parent`, and so on. Deferring the call to first read breaks that chain — and, for
         * every property, still holds the value rather than recomputing it, [LazyFake] itself doing
         * what a plain initializer's backing field otherwise would.
         *
         * A `Nothing`-typed property (`val impossible: Nothing`) is the other exception: no value of
         * that type exists to hold or defer, so instead of an initializer it gets a getter that
         * throws — `override val impossible: Nothing get() = throw ...` — the same "throws if
         * reached, but doesn't stop the fake from being constructed" contract a `Nothing`-returning
         * function gets (see [fakedFunction]). A backing-field-less `var` also needs an explicit
         * (no-op) setter, same as the `LazyFake` case needs none — [LazyFake] is itself the backing
         * field there.
         */
        private fun fakedProperty(vProp: KSPropertyDeclaration, vPropType: KSType, filesDeps: MutableSet<KSFile>): PropertySpec {
            val (template, values) = fakeValueOf(vPropType, filesDeps)
            val builder = PropertySpec.builder(vProp.simpleName.asString(), vPropType.toMemberTypeName())
                .addModifiers(KModifier.OVERRIDE)
                .mutable(vProp.isMutable)
                .addAnnotations(vProp.overrideAnnotations())
            return when {
                vPropType.isNothing() -> builder
                    .getter(FunSpec.getterBuilder().addStatement(template, *values.toTypedArray()).build())
                    .apply {
                        if (vProp.isMutable) setter(FunSpec.setterBuilder().addParameter("value", vPropType.toMemberTypeName()).build())
                    }
                    .build()
                vPropType.needsLazyFake() ->
                    builder.delegate("%T { $template }", lazyFakeTypeName, *values.toTypedArray()).build()
                else -> builder.initializer(template, *values.toTypedArray()).build()
            }
        }

        /**
         * The no-op override of one abstract function of an implemented interface or abstract class,
         * e.g. for `fun log(m: String)`, `fun count(): Int` and `fun user(): User`:
         *
         * ```
         * override fun log(m: String) {}
         * override fun count(): Int = 0
         * override fun user(): User = fakeUser()
         * ```
         *
         * Parameter and return types come from [vFunSig] — the signature *as a member of* the
         * implemented instantiation — so a generic supertype's parameters are substituted; the
         * function's own type parameters are the ones [vFunSig] deliberately leaves alone, and are
         * re-declared on the override.
         *
         * A function returning one of those own type parameters is given the parameter that already
         * holds a value of that very type, when it has one — `fun <T> convert(value: T): T` fakes as
         * `= value`, the only answer that can be right for every `T` a caller may ask for, and an
         * inert one. Failing that, it gets a throwing body: nothing can produce an `R` out of thin
         * air, and the alternative — faking `R`'s bound and casting — would only move the failure to
         * the call site, as a `ClassCastException`.
         */
        private fun fakedFunction(vFun: KSFunctionDeclaration, vFunSig: KSFunction, filesDeps: MutableSet<KSFile>): FunSpec {
            val gFun = FunSpec.builder(vFun.simpleName.asString())
                .addModifiers(KModifier.OVERRIDE)
            val typeParamResolver = vFun.typeParameters.toTypeParameterResolver()
            vFun.typeParameters.forEach { vParam -> gFun.addTypeVariable(vParam.toTypeVariableName(typeParamResolver)) }
            gFun.addModifiers((vFun.modifiers - Modifier.ABSTRACT - Modifier.OPEN - Modifier.OPERATOR).mapNotNull { it.toKModifier() })
            gFun.addAnnotations(vFun.overrideAnnotations())
            val vParamTypes = vFun.parameters.mapIndexed { index, vParam -> vFunSig.parameterTypes.getOrNull(index) ?: vParam.type.resolve() }
            vFun.parameters.forEachIndexed { index, vParam ->
                gFun.addParameter(
                    vParam.name!!.asString(),
                    vParamTypes[index].toMemberTypeName(typeParamResolver),
                    if (vParam.isVararg) listOf(KModifier.VARARG) else emptyList()
                )
            }

            val vReturnType = vFunSig.returnType ?: vFun.returnType!!.resolve()
            gFun.returns(vReturnType.toMemberTypeName(typeParamResolver))
            when {
                vReturnType.isUnit() -> {} // No body at all: a no-op function is what this generates.
                vReturnType.isNothing() -> {
                    // `return $template` would emit `return throw ...`, whose `return` is
                    // unreachable and triggers a compiler warning; the throw alone is a valid body.
                    val (template, values) = fakeValueOf(vReturnType, filesDeps)
                    gFun.addStatement(template, *values.toTypedArray())
                }
                vReturnType.mentionsTypeParameter() -> {
                    // Nullability is part of KSType equality, so a `T?` parameter is not returned as
                    // a `T`. A vararg is excluded because KSP reports its element type: the generated
                    // parameter is an `Array<out T>`, which is not the `T` being returned.
                    val vReturned = vFun.parameters.filterIndexed { index, vParam ->
                        !vParam.isVararg && vParamTypes[index] == vReturnType
                    }.firstOrNull()
                    if (vReturned != null) {
                        // %N, not %L: KotlinPoet escapes a parameter named `value` in the signature it
                        // just generated, and this reference has to be escaped identically.
                        gFun.addStatement("return %N", vReturned.name!!.asString())
                    } else {
                        gFun.addStatement(
                            "return error(%S)",
                            "Cannot fake ${vFun.simpleName.asString()}(): MocKMP cannot produce a value of its generic return type ${vReturnType.toMemberTypeName(typeParamResolver)}."
                        )
                    }
                }
                else -> {
                    val (template, values) = fakeValueOf(vReturnType, filesDeps)
                    gFun.addStatement("return $template", *values.toTypedArray())
                }
            }
            return gFun.build()
        }

        /**
         * Adds the `FakeXxx` class implementing interface (or extending abstract class) [vCls] to
         * [gFile], and appends `return FakeXxx()` to [gFun] — the path taken for a type that cannot
         * be constructed but *can* be implemented:
         *
         * ```
         * internal class FakeApi : Api {
         *     override val name: String = ""
         *     override fun log(m: String) {}
         *     override fun user(): User = fakeUser()
         * }
         *
         * internal fun fakefoo_Api(): Api = FakeApi()
         * ```
         *
         * Only *abstract* members are overridden: an interface's default implementations are left to
         * run, over the faked abstract members they are written in terms of. Overriding them too
         * would gain nothing (a default member of a fake is inert already, if its abstract members
         * are) and can outright fail to compile, as the JDK interop members mock generation ran into
         * (see [generateMockClass]).
         *
         * The class is generated per faked *instantiation* rather than being generic — `FakeItfXkotlin_StringX
         * : Itf<String>` — since, unlike a `MockXxx`, it has to hold real values, and no value of a
         * type parameter can be produced. Its members are resolved against
         * [KSType.withBoundArguments], the instantiation actually implemented.
         */
        private fun addFakeImplementation(gFile: FileSpec.Builder, gFun: FunSpec.Builder, vCls: KSClassDeclaration, vType: KSType, filesDeps: MutableSet<KSFile>, process: ToProcess) {
            val implementedType = vType.withBoundArguments()
            val fakeClassName = vType.toFakeClassName()
            val gCls = TypeSpec.classBuilder(fakeClassName).addModifiers(visibilityModifier)

            if (vCls.classKind == ClassKind.INTERFACE) {
                gCls.addSuperinterface(implementedType.toTypeName())
            } else {
                if (vCls.firstPublicConstructor() == null) {
                    reportUnfakeable(gFun, vCls, "it has no public constructor", process)
                    return
                }
                gCls.superclass(implementedType.toTypeName())
                addSuperclassConstructorArgs(gCls, vCls, implementedType, filesDeps)
            }

            val vProps = vCls.getAllProperties().filter { it.isAbstract() }.toList()
            val vFuns = vCls.getAllFunctions().filter { it.isAbstract }.toList()

            // Same trade-off as [generateMockClass]: [overrideAnnotations] drops `kotlin.Deprecated`,
            // which leaves the override warning that it does not repeat its supertype's deprecation.
            if (vProps.any { it.isDeprecated() } || vFuns.any { it.isDeprecated() }) {
                gCls.addAnnotation(
                    AnnotationSpec.builder(Suppress::class).addMember("%S", "OVERRIDE_DEPRECATION").build()
                )
            }

            vProps.forEach { vProp -> gCls.addProperty(fakedProperty(vProp, vProp.asMemberOf(implementedType), filesDeps)) }
            vFuns.forEach { vFun ->
                // A supertype re-declaring equals/hashCode as abstract forces an override; faking one
                // would break the very identity the fake is looked up by, exactly as it would a mock.
                if (vFun.simpleName.asString() in IDENTITY_MEMBERS) addIdentityOverride(gCls, vFun, vCls)
                else gCls.addFunction(fakedFunction(vFun, vFun.asMemberOf(implementedType), filesDeps))
            }

            gFile.addType(gCls.build())
            gFun.addStatement("return %N()", fakeClassName)
        }

        /**
         * Appends `return Xxx.FIRST` to [gFun] — the first declared entry of enum [vCls] — or, for
         * an *implicit* target with no entries, [reportUnfakeable] instead of aborting the
         * KSP round.
         */
        private fun addFakeFirstEnumEntry(gFun: FunSpec.Builder, vCls: KSClassDeclaration, process: ToProcess) {
            val firstEntry = vCls.declarations.filterIsInstance<KSClassDeclaration>().firstOrNull { it.classKind == ClassKind.ENUM_ENTRY }
            if (firstEntry == null) {
                reportUnfakeable(gFun, vCls, "it is an empty enum class", process)
                return
            }
            gFun.addStatement("return %T.%L", vCls.toClassName(), firstEntry.simpleName.asString())
        }

        /**
         * Generates the top-level `fakeXxx(): Xxx` function for [vType], into its own file. Sealed
         * classes/interfaces are first resolved to their first constructible permitted subclass, with
         * that subclass's own type arguments (see [resolveSealedTargetType]) — a class or annotation
         * class fake constructs the type via [addFakeClassConstructorCall] (an annotation class's
         * constructor is called the same way any other class's is, only its declared parameter
         * types differ), an enum fake returns its first entry via [addFakeFirstEnumEntry], an object
         * fake is a plain reference, and an interface or abstract class fake instantiates the
         * `FakeXxx` implementation [addFakeImplementation] generates into the same file:
         *
         * ```
         * internal fun fakeFoo(): Foo = Foo(bar = "")
         * internal fun fakeDirection(): Direction = Direction.NORTH
         * internal fun fakeSCls(): SCls = SCls.O
         * internal fun fakeSingleton(): Singleton = Singleton
         * internal fun fakeAnno(): Anno = Anno(name = "")
         * internal fun fakeApi(): Api = FakeApi()
         * ```
         *
         * Records the generated function name into [fakes], consumed by [generateFakeAccessor].
         */
        private fun generateFakeFunction(vType: KSType, process: ToProcess) {
            val vCls = vType.declaration as KSClassDeclaration
            val targetType = resolveSealedTargetType(vType)
            val targetCls = targetType.declaration as KSClassDeclaration
            val filesDeps = LinkedHashSet(process.files)
            val mockFunName = "fake${vType.toFunName()}"
            val mockPkg = vCls.fakePackageName()
            val gFile = FileSpec.builder(mockPkg, mockFunName)
            val gFun = FunSpec.builder(mockFunName)
                .addModifiers(visibilityModifier)
                .returns(vType.toTypeName(vCls.typeParameters.toTypeParameterResolver()))
            when {
                targetCls.isFakedByImplementing() -> addFakeImplementation(gFile, gFun, targetCls, targetType, filesDeps, process)
                targetCls.classKind == ClassKind.ANNOTATION_CLASS ||
                        (targetCls.classKind == ClassKind.CLASS && Modifier.SEALED !in targetCls.modifiers) ->
                    addFakeClassConstructorCall(gFun, targetCls, targetType, filesDeps, process)
                targetCls.classKind == ClassKind.ENUM_CLASS -> addFakeFirstEnumEntry(gFun, targetCls, process)
                targetCls.classKind == ClassKind.OBJECT -> gFun.addStatement("return %T", targetCls.toClassName())
                else -> {
                    val reason = when {
                        targetCls != vCls -> "MocKMP resolved it to its permitted subclass ${targetCls.displayName()}, and ${targetCls.classKind.plural()} cannot be instantiated"
                        Modifier.SEALED in vCls.modifiers -> "it is a sealed ${vCls.classKind.type} with no permitted subclasses"
                        else -> "${targetCls.classKind.plural()} cannot be instantiated"
                    }
                    reportUnfakeable(gFun, vCls, reason, process)
                }
            }
            gFile.addFunction(gFun.build().also { fakes[vType] = MemberName(mockPkg, mockFunName) })
            gFile.build().writeTo(codeGenerator, Dependencies(true, *filesDeps.toTypedArray()))
        }

