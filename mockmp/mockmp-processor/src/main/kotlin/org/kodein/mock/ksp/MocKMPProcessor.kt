            "kotlinx.coroutines.Job" to Builtin("%M()", MemberName("kotlinx.coroutines", "Job"), external = true),
            "kotlinx.coroutines.CompletableJob" to Builtin("%M()", MemberName("kotlinx.coroutines", "Job"), external = true),
