        // region Phase 1.5: implicit placeholders

        /**
         * A representative [KSType] for [this] declaration, substituting each type parameter with
         * its first bound (e.g. `T : Any` becomes `Any`) — the same "good enough" stand-in
         * [generateMockAccessor] already uses when the concrete type argument is unknown.
         */
        private fun KSClassDeclaration.asBoundedType(): KSType =
            asType(typeParameters.map { resolver.getTypeArgument(it.bounds.first(), Variance.INVARIANT) })

        /** The stand-in type for [this] type parameter when no argument is known: its first bound, or `Any?`. */
        private fun KSTypeParameter.boundType(): KSType =
            bounds.firstOrNull()?.resolve() ?: resolver.builtIns.anyType.makeNullable()

        /**
         * [this] type with every star projection — and every argument missing altogether — replaced
         * by the matching parameter's bound, as [asBoundedType] does.
         *
         * What a generated fake implementation is written against: a class cannot declare a
         * star-projected supertype (`class FakeItf : Itf<*>` does not compile), and a member's type
         * cannot be substituted through one either. `Itf<Any>` is the closest implementable
         * instantiation, and remains a subtype of the `Itf<*>` its `fakeXxx()` function returns.
         */
        private fun KSType.withBoundArguments(): KSType {
            val decl = declaration as? KSClassDeclaration ?: return this
            if (decl.typeParameters.isEmpty()) return this
            if (arguments.size != decl.typeParameters.size) return decl.asBoundedType()
            if (arguments.none { it.variance == Variance.STAR || it.type == null }) return this
            val boundArguments = decl.typeParameters.zip(arguments).map { (vParam, argument) ->
                if (argument.variance != Variance.STAR && argument.type != null) argument
                else resolver.getTypeArgument(resolver.createKSTypeReferenceFromKSType(vParam.boundType()), Variance.INVARIANT)
            }
            return replace(boundArguments)
        }

        /** True when [this] type is, or contains at any depth, a reference to a type parameter. */
        private fun KSType.mentionsTypeParameter(): Boolean =
            declaration is KSTypeParameter || arguments.any { it.type?.resolve()?.mentionsTypeParameter() == true }

        /**
         * [this] type, rendered for a generated *member signature*.
         *
         * Identical to [toTypeName] except for function types, which are written back as lambdas:
         * KSP resolves them to their underlying declaration, which `toTypeName` then renders
         * literally — `Function1<String, Int>` for `(String) -> Int`, which merely reads oddly, but
         * `SuspendFunction1<String, Int>` for `suspend (String) -> Int`, which is a
         * compiler-internal declaration that cannot be written in Kotlin source at all.
         *
         * Member types have to go through this because they come from
         * [KSPropertyDeclaration.asMemberOf], which yields a [KSType] with the declared syntax lost;
         * mocked members keep theirs by rendering their [KSTypeReference] instead.
         */
        private fun KSType.toMemberTypeName(typeParamResolver: TypeParameterResolver = TypeParameterResolver.EMPTY): TypeName {
            if (!isAnyFunctionType) return toTypeName(typeParamResolver)
            val argumentTypes = arguments.map { it.type!!.resolve().toMemberTypeName(typeParamResolver) }
            // `A.() -> B` and `(A) -> B` share one underlying declaration, told apart only by this
            // annotation; an override has to repeat the form its supertype declares.
            val isExtension = annotations.any { it.shortName.asString() == "ExtensionFunctionType" }
            val parameterTypes = argumentTypes.dropLast(1)
            return LambdaTypeName.get(
                receiver = if (isExtension) parameterTypes.first() else null,
                parameters = (if (isExtension) parameterTypes.drop(1) else parameterTypes).map { ParameterSpec.unnamed(it) },
                returnType = argumentTypes.last(),
            ).copy(suspending = isSuspendFunctionType, nullable = isMarkedNullable)
        }

        /**
         * True when every type argument of [this] is its own parameter's bound (`GenData<Any>` for
         * `GenData<out T : Any>`) — the most general instantiation, and what [asBoundedType] builds.
         * Trivially true for a non-generic type.
         */
        private fun KSType.isBoundedInstantiation(): Boolean {
            val decl = declaration as? KSClassDeclaration ?: return false
            if (arguments.size != decl.typeParameters.size) return false
            return decl.typeParameters.zip(arguments).all { (vParam, argument) -> argument.type?.resolve() == vParam.boundType() }
        }

        /**
         * If [decl] is sealed (class or interface), returns its first permitted subclass, resolved
         * recursively through nested sealed hierarchies. Returns [decl] unchanged when it isn't
         * sealed, or when a sealed hierarchy has no permitted subclasses (construction then fails
         * naturally later, with a reasonable "no public constructor" message).
         *
         * [resolveSealedTargetType] is the type-level counterpart, and must keep picking the same
         * subclass as this one.
         */
        private fun resolveSealedTarget(decl: KSClassDeclaration): KSClassDeclaration {
            if (Modifier.SEALED !in decl.modifiers) return decl
            val first = decl.getSealedSubclasses().firstOrNull() ?: return decl
            return resolveSealedTarget(first)
        }

        /**
         * Binds the type parameters [declared] is written in terms of to the matching arguments of
         * [actual], recursively — unifying `Swapped<Y, X>` against `Swapped<String, Int>` binds
         * `Y` to `String` and `X` to `Int`.
         */
        private fun bindTypeParameters(declared: KSType, actual: KSType, into: MutableMap<KSTypeParameter, KSType>) {
            val decl = declared.declaration
            if (decl is KSTypeParameter) {
                into[decl] = actual
                return
            }
            declared.arguments.forEachIndexed { index, argument ->
                val declaredArgument = argument.type?.resolve() ?: return@forEachIndexed
                val actualArgument = actual.arguments.getOrNull(index)?.type?.resolve() ?: return@forEachIndexed
                bindTypeParameters(declaredArgument, actualArgument, into)
            }
        }

        /**
         * [resolveSealedTarget] at the type level: the permitted subclass that will actually be
         * constructed for [vType], expressed with *its own* type arguments.
         *
         * A subclass does not have to declare the same type parameters, in the same order, as the
         * sealed parent it extends — `class Impl<X, Y> : Swapped<Y, X>()` is legal — so the parent's
         * arguments cannot simply be indexed by the subclass's parameter positions. They are mapped
         * through the supertype reference the subclass declares ([bindTypeParameters]); a parameter
         * the parent says nothing about falls back to its bound.
         */
        private fun resolveSealedTargetType(vType: KSType): KSType {
            val decl = vType.declaration as? KSClassDeclaration ?: return vType
            if (Modifier.SEALED !in decl.modifiers) return vType
            val sub = decl.getSealedSubclasses().firstOrNull() ?: return vType

            val bindings = HashMap<KSTypeParameter, KSType>()
            sub.superTypes
                .map { it.resolve() }
                .firstOrNull { it.declaration == decl }
                ?.let { bindTypeParameters(it, vType, bindings) }
            val arguments = sub.typeParameters.map { vParam ->
                resolver.getTypeArgument(
                    resolver.createKSTypeReferenceFromKSType(bindings[vParam] ?: vParam.boundType()),
                    Variance.INVARIANT,
                )
            }
            return resolveSealedTargetType(sub.asType(arguments))
        }

        /**
         * Registers one type reachable from a mocked interface's signatures as needing a
         * placeholder, unless it's already covered: [builtins], an existing [toMock] entry, or an
         * existing [toFake] entry. Nullable types need no placeholder (`null` is a valid one). An
         * unresolved type parameter is substituted with its first bound, same as [asBoundedType].
         *
         * The dispatch *key* is always the original type — the one `isAny<T>()`/etc. will actually
         * ask for at runtime (e.g. `SItf::class`, not `SItf.C::class`) — even when [resolveSealedTarget]
         * means the *generated body* ends up constructing a different, concrete permitted subclass;
         * [generateFakeFunction] already does this same redirection internally.
         *
         * `kotlin.Array<T>` gets dedicated handling in [placeholderArrayTypes]: unlike ordinary
         * generics, it isn't erased on the JVM, so a single shared `Array::class` branch can't work
         * for every component type.
         *
         * Function types get dedicated handling in [placeholderFunctionShapes] too — not because
         * `T::class` is any different for them (it erases to `kotlin.Function1`/etc. exactly like
         * any other interface), but because *constructing* a value is: Kotlin/JS forbids a class
         * declaring `: Function1<P1, R>` as a supertype ("Implementing a function interface is
         * prohibited in JavaScript"), so the placeholder for a function-typed target has to be a
         * plain lambda rather than a `MockXxx` class.
         */
        private fun registerFunctionShape(resolved: KSType) {
            val decl = resolved.declaration as? KSClassDeclaration ?: return
            placeholderFunctionShapes[decl] = resolved.isSuspendFunctionType to (resolved.arguments.size - 1)
        }

        private fun seedImplicitPlaceholder(type: KSType, path: List<String>) {
            if (type.nullability != Nullability.NOT_NULL) return
            var resolved = type.unwrapAliases()
            if (resolved.isAnyFunctionType) {
                registerFunctionShape(resolved)
                return
            }
            if (resolved.declaration is KSTypeParameter) {
                resolved = (resolved.declaration as KSTypeParameter).bounds.first().resolve().unwrapAliases()
                if (resolved.isAnyFunctionType) {
                    registerFunctionShape(resolved)
                    return
                }
            }
            val decl = resolved.declaration
            if (decl !is KSClassDeclaration) return
            if (decl.qualifiedName?.asString() == "kotlin.Array") {
                // `Array<*>` has no component type to key a component-specific branch on — which is
                // the only reason [placeholderArrayTypes] exists — so leave it to the generic
                // `Array::class -> emptyArray<Any?>()` builtin branch, exactly as any other erased
                // generic is handled.
                if (resolved.arguments.firstOrNull()?.type != null) placeholderArrayTypes += resolved
                return
            }
            if (decl.qualifiedName?.asString() in builtins) return
            if (decl in toMock || resolved in toFake) return
            val target = resolveSealedTarget(decl)
            when {
                target != decl -> toFake[resolved] = ToProcess().apply { implicit = true; this.path = path }
                decl.classKind == ClassKind.INTERFACE || (decl.classKind == ClassKind.CLASS && Modifier.ABSTRACT in decl.modifiers) ->
                    toMock[decl] = ToProcess().apply { implicit = true; this.path = path }
                decl.classKind == ClassKind.CLASS || decl.classKind == ClassKind.ENUM_CLASS ->
                    toFake[resolved] = ToProcess().apply { implicit = true; this.path = path }
                else -> {}
            }
        }

        /**
         * Walks every interface/abstract class already in [toMock] and seeds a placeholder for
         * every parameter, return, and property type reachable from its members — the set of types
         * `isAny()`/`isEqual()`/etc. may need to return a value for. For an *implicit* entry, only
         * abstract members are walked, mirroring [generateMockClass]'s decision to only override
         * abstract members for such a target — walking (and then generating an override for) a JDK
         * default method like `Iterable.forEach(Consumer)` has repeatedly proven to be a source of
         * variance conflicts and out-of-bounds package restrictions for no benefit, since a
         * placeholder is never meant to be genuinely invoked anyway. Runs as a worklist since a
         * newly-seeded abstract class or interface may itself reference further types.
         */
        private fun seedImplicitPlaceholders() {
            val toExplore = ArrayDeque(toMock.keys)
            while (toExplore.isNotEmpty()) {
                val vItf = toExplore.removeFirst()
                val process = toMock.getValue(vItf)
                val overrideAll = vItf.classKind == ClassKind.INTERFACE && !process.implicit
                val owner = vItf.simpleName.asString()
                val before = HashSet(toMock.keys)
                vItf.getAllProperties()
                    .filter { it.isAbstract() }
                    .forEach { vProp ->
                        val vPropType = vProp.type.resolve()
                        seedImplicitPlaceholder(vPropType, process.path + propertyPathStep(owner, vProp, vPropType))
                    }
                vItf.getAllFunctions()
                    .filter { it.simpleName.asString() !in IDENTITY_MEMBERS && (overrideAll || it.isAbstract) }
                    .forEach { vFun ->
                        val vParamTypes = vFun.parameters.map { it.type.resolve() }
                        val vReturnType = vFun.returnType?.resolve()
                        // One step for the whole member: which of its types needed the placeholder is
                        // not what a reader is after — where it came from is.
                        val path = process.path + functionPathStep(owner, vFun, vParamTypes, vReturnType)
                        vParamTypes.forEach { seedImplicitPlaceholder(it, path) }
                        vReturnType?.let { seedImplicitPlaceholder(it, path) }
                    }
                toMock.keys.forEach { if (it !in before) toExplore.add(it) }
            }
        }

