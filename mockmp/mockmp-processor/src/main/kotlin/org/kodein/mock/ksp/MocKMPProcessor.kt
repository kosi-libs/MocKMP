        // region Phase 5: injectors

        /**
         * Appends the `@Mock` assignment for [vProp] to [gFun]: a `mockFunctionN(...)` call when
         * [vPropType] is itself a function type (a mocked callback property), or `MockXxx(this)`
         * otherwise.
         */
        private fun addMockInjection(gFun: FunSpec.Builder, vProp: KSPropertyDeclaration, vPropType: KSType) {
            val vPropTypeDecl = vPropType.declaration
            if (vPropType.isFunctionType) {
                val argCount = vPropType.arguments.size - 1
                val args =
                    if (argCount == 0) ""
                    else vPropType.arguments.take(argCount).joinToString(prefix = ", ") { "\"${it.type!!.resolve().declaration.qualifiedName!!.asString()}\"" }
                gFun.addStatement(
                    "receiver.%N = %M(this$args)",
                    vProp.simpleName.asString(),
                    MemberName("org.kodein.mock", "mockFunction$argCount"),
                )
            } else {
                gFun.addStatement(
                    "receiver.%N = %T(this)",
                    vProp.simpleName.asString(),
                    ClassName(vPropTypeDecl.packageName.asString(), vPropTypeDecl.toMockName()),
                )
            }
        }

        /** Appends the `@Fake` assignment for [vProp] to [gFun], via [fakeInitializerOf]. */
        private fun addFakeInjection(gFun: FunSpec.Builder, vProp: KSPropertyDeclaration, vPropType: KSType, filesDeps: MutableSet<KSFile>) {
            val (template, value) = fakeInitializerOf(vPropType, filesDeps)
            gFun.addStatement("receiver.%N = $template", vProp.simpleName.asString(), value)
        }

        /**
         * Every `@Mock`/`@Fake` annotated property that is *visible* on [vCls]: the ones it declares
         * itself, plus the ones it inherits from its supertypes.
         *
         * [toInject] is keyed by declaring class, so without this merge a subclass's injector would
         * set only its own properties — and since the user's `mocker.injectMocks(this)` resolves to
         * the most specific overload, inherited properties would stay uninitialized.
         *
         * Supertypes come first so that, if a subclass shadows an inherited annotated property, the
         * derived declaration is the one kept: the generated `receiver.name = …` always resolves to
         * the most derived property anyway, so entries are deduplicated by simple name, last wins.
         */
        private fun injectedPropertiesOf(vCls: KSClassDeclaration): List<Pair<String, KSPropertyDeclaration>> {
            val ancestors = vCls.getAllSuperTypes()
                .mapNotNull { it.declaration as? KSClassDeclaration }
                .toList()
                .asReversed()
            return (ancestors + vCls)
                .flatMap { toInject[it] ?: emptyList() }
                .associateBy { (_, vProp) -> vProp.simpleName.asString() }
                .values
                .toList()
        }

        /**
         * Generates `Mocker.injectMocks(receiver: Xxx)` for class [vCls], setting every
         * `@Mock`/`@Fake` annotated property visible on it — inherited ones included, see
         * [injectedPropertiesOf]:
         *
         * ```
         * internal fun Mocker.injectMocks(receiver: SomeTests) {
         *     receiver.foo = MockFoo(this)
         *     receiver.bar = fakeBar()
         * }
         * ```
         */
        private fun generateInjector(vCls: KSClassDeclaration) {
            val vProps = injectedPropertiesOf(vCls)
            val filesDeps = HashSet<KSFile>().apply {
                vCls.containingFile?.let { add(it) }
                // An inherited property is declared in another file: its change must retrigger this generation.
                vProps.forEach { (_, vProp) -> vProp.containingFile?.let { add(it) } }
            }

            val gFile = FileSpec.builder(vCls.packageName.asString(), "${vCls.simpleName.asString()}_injectMocks")
            val gFun = FunSpec.builder("injectMocks")
                .addModifiers(visibilityModifier)
                .receiver(mockerTypeName)
                .addParameter("receiver", vCls.toClassName())
            vProps.forEach { (anno, vProp) ->
                val vPropType = vProp.type.resolve()
                when (anno) {
                    ANNOTATION_MOCK -> addMockInjection(gFun, vProp, vPropType)
                    ANNOTATION_FAKE -> addFakeInjection(gFun, vProp, vPropType, filesDeps)
                }
            }
            gFile.addFunction(gFun.build())
            gFile.build().writeTo(codeGenerator, Dependencies(true, *filesDeps.toTypedArray()))
        }

        // endregion

        // region Phase 6: accessors

        /**
         * A [FunSpec.Builder] for accessor function [name], with [visibilityModifier] applied and,
         * in multiplatform projects, `actual` — matching the `expect` declaration generated by the
         * MocKMP Gradle plugin (see `mockmp-gradle-plugin/src/main/resources/mockmp.multi.kt`).
         */
        private fun accessorFunBuilder(name: String): FunSpec.Builder {
            val gFun = FunSpec.builder(name).addModifiers(visibilityModifier)
            if (multiplatform) gFun.addModifiers(KModifier.ACTUAL)
            return gFun
        }

        /**
         * Generates the `Mocker.mock(KClass<T>): T` dispatcher, with one `when` branch per mocked
         * interface:
         *
         * ```
         * internal actual fun <T : Any> Mocker.mock(type: KClass<T>): T = when (type) {
         *     Foo::class -> MockFoo(this) as T
         *     else -> error("Could not find mock for type $type")
         * }
         * ```
         */
        private fun generateMockAccessor() {
            @Suppress("LocalVariableName")
            val T = TypeVariableName("T", Any::class)
            val gFile = FileSpec.builder(accessorsPackage, "mocks")
            val gFun = accessorFunBuilder("mock")
                .receiver(mockerTypeName)
                .addParameter("type", KClass::class.asTypeName().parameterizedBy(T))
                .addTypeVariable(T)
                .returns(T)

            if (mocks.isNotEmpty()) {
                gFun.addAnnotation(AnnotationSpec.builder(Suppress::class).addMember("%S", "UNCHECKED_CAST").build())
                gFun.beginControlFlow("return when (type)")
                mocks.forEach { (itf, mock) ->
                    val mockTypeName: TypeName =
                        if (itf.typeParameters.isNotEmpty()) {
                            mock.parameterizedBy(*itf.typeParameters.map { it.bounds.first().resolve().toTypeName() }.toTypedArray())
                        } else {
                            mock
                        }
                    gFun.addStatement("%T::class -> %T(this) as T", itf.toClassName(), mockTypeName)
                }
                gFun.addStatement("else -> error(\"Could not find mock for type \$type\")")
                gFun.endControlFlow()
            } else {
                gFun.addStatement("error(\"No mocks declared\")")
            }

            gFile.addFunction(gFun.build())
            gFile.build().writeTo(codeGenerator, Dependencies(true))
        }

        /**
         * Generates the `fake(KType): T` dispatcher, with one `when` branch per faked type, keyed
         * by a generated `private val type_pkg_Xxx: KType = typeOf<Xxx>()` (faked types can be
         * generic, and `KType` equality — unlike [KClass] — accounts for type arguments). The
         * package is folded into the name (via [toFunName]) because every one of these properties
         * lives in the same generated `fakes.kt` file, where a bare simple name is not unique
         * (`foo.Data` and `bar.Data` would otherwise both want `type_Data`):
         *
         * ```
         * private val type_foo_Foo: KType = typeOf<foo.Foo>()
         * internal actual fun <T : Any> fake(type: KType): T = when (type) {
         *     type_foo_Foo -> fakefoo_Foo() as T
         *     else -> error("Could not find fake for type $type")
         * }
         * ```
         */
        private fun generateFakeAccessor() {
            @Suppress("LocalVariableName")
            val T = TypeVariableName("T", Any::class)
            val gFile = FileSpec.builder(accessorsPackage, "fakes")
            fakes.forEach { (type, _) ->
                gFile.addProperty(
                    PropertySpec.builder("type_${type.toFunName()}", KType::class)
                        .addModifiers(KModifier.PRIVATE)
                        .initializer("%M<%T>()", MemberName("kotlin.reflect", "typeOf"), type.toTypeName())
                        .build()
                )
            }
            val gFun = accessorFunBuilder("fake")
                .addAnnotation(AnnotationSpec.builder(Suppress::class).addMember("%S", "UNCHECKED_CAST").build())
                .addParameter("type", KType::class.asTypeName())
                .addTypeVariable(T)
                .returns(T)

            if (fakes.isNotEmpty()) {
                gFun.beginControlFlow("return when (type)")
                fakes.forEach { (type, fake) -> gFun.addStatement("type_${type.toFunName()} -> %M() as T", fake) }
                gFun.addStatement("else -> error(\"Could not find fake for type \$type\")")
                gFun.endControlFlow()
            } else {
                gFun.addStatement("error(\"No fakes declared\")")
            }
            gFile.addFunction(gFun.build())
            gFile.build().writeTo(codeGenerator, Dependencies(true))
        }

        /**
         * Generates the `Mocker.injectMocks(receiver: Any)` dispatcher, with one `when` branch per
         * class that has injected properties:
         *
         * ```
         * internal actual fun Mocker.injectMocks(receiver: Any) = when (receiver) {
         *     is SomeTests -> injectMocks(receiver)
         *     else -> error("Could not find injector for $receiver")
         * }
         * ```
         *
         * Only the first matching branch of a `when` ever runs, so branches are ordered most derived
         * first: a class always has strictly more supertypes than any of its own supertypes, which
         * makes "supertype count, descending" a valid topological order. Unrelated classes are then
         * ordered by qualified name, so the generated file does not depend on [toInject]'s hash order.
         */
        private fun generateInjectorAccessor() {
            val gFile = FileSpec.builder(accessorsPackage, "injectors")
            val gFun = accessorFunBuilder("injectMocks")
                .receiver(mockerTypeName)
                .addParameter("receiver", Any::class)

            if (toInject.isNotEmpty()) {
                val sorted = toInject.keys.sortedWith(
                    compareByDescending<KSClassDeclaration> { it.getAllSuperTypes().count() }
                        .thenBy { it.qualifiedName?.asString() ?: it.simpleName.asString() }
                )
                gFun.beginControlFlow("return when (receiver)")
                sorted.forEach { cls -> gFun.addStatement("is %T -> %M(receiver)", cls.toClassName(), MemberName(cls.packageName.asString(), "injectMocks")) }
                gFun.addStatement("else -> error(\"Could not find injector for \$receiver\")")
                gFun.endControlFlow()
            } else {
                gFun.addStatement("error(\"No injectors declared\")")
            }
            gFile.addFunction(gFun.build())
            gFile.build().writeTo(codeGenerator, Dependencies(true))
        }

        /**
         * Generates the `providePlaceholder(KClass<*>): Any` dispatcher — the replacement for the
         * unsafe-cast placeholder mechanism this used to rely on. Every generated `MockXxx` class
         * registers this on its `mocker` (see [mockClassBuilder]'s `init` block), so it's what
         * `References` falls back to when it has no builtin and no user-registered reference for a
         * type — i.e. what `isAny()`/`isEqual()`/etc. need to return from inside an `every { }`.
         *
         * One `when` branch per: mocked interface/abstract class (`MockFoo(Mocker())`), fake
         * class/enum (`fakeFoo()`, deduped to one representative per raw class since `KClass`
         * erases generic type arguments — see [fakes]), concrete array type (see
         * [placeholderArrayTypes] — `Array<T>` is the one case that *isn't* erased on the JVM),
         * function-type arity (a plain lambda cast to the right shape, matched by the same raw
         * `Function1::class`/etc. `T::class` already erases to — see [placeholderFunctionShapes];
         * one branch per `KClass`, a suspend shape's JVM fallback key never displacing a genuine one),
         * and non-numeric builtin (a literal or factory call matching [builtins] — the numeric ones
         * are already handled by `References`'s own hardcoded primitive map and never reach here):
         *
         * ```
         * internal actual fun providePlaceholder(cls: KClass<*>): Any = when (cls) {
         *     Bar::class -> MockBar(Mocker())
         *     Function1::class -> ({ _ -> error("...") }) as (Any?) -> Any?
         *     Data::class -> fakeData()
         *     String::class -> ""
         *     else -> error("Could not find placeholder for type $cls")
         * }
         * ```
         */
        private fun generatePlaceholderAccessor() {
            val gFile = FileSpec.builder(accessorsPackage, "placeholders")
            val gFun = accessorFunBuilder("providePlaceholder")
                .addAnnotation(AnnotationSpec.builder(Suppress::class).addMember("%S", "UNCHECKED_CAST").build())
                .addParameter("cls", KClass::class.asTypeName().parameterizedBy(STAR))
                .returns(Any::class)

            gFun.beginControlFlow("return when (cls)")

            mocks.forEach { (itf, mock) ->
                val mockTypeName: TypeName =
                    if (itf.typeParameters.isNotEmpty()) {
                        mock.parameterizedBy(*itf.typeParameters.map { it.bounds.first().resolve().toTypeName() }.toTypedArray())
                    } else {
                        mock
                    }
                gFun.addStatement("%T::class -> %T(%T())", itf.toClassName(), mockTypeName, mockerTypeName)
            }

            // A fake keyed by a sealed type (e.g. SItf) is generated by constructing a concrete
            // permitted subclass (SItf.C — see resolveSealedTarget). Register both KClasses against
            // the same function: isAny<SItf>() asks for the former, isInstanceOf<SItf.C>() the latter.
            val fakesByDecl = LinkedHashMap<KSClassDeclaration, MemberName>()
            fakes.forEach { (type, member) ->
                val decl = type.declaration as? KSClassDeclaration ?: return@forEach
                fakesByDecl.getOrPut(decl) { member }
                val target = resolveSealedTarget(decl)
                if (target != decl) fakesByDecl.getOrPut(target) { member }
            }
            fakesByDecl.forEach { (decl, member) -> gFun.addStatement("%T::class -> %M()", decl.toClassName(), member) }

            // isInstanceOf<T>()/isEqual<T>() can also target one of a sealed type's OTHER permitted
            // subclasses — not just the one resolveSealedTarget picked for the fake function above.
            // An object subclass needs no function call at all: just reference the singleton.
            val sealedObjectSubclasses = LinkedHashSet<KSClassDeclaration>()
            fakes.keys.mapNotNull { it.declaration as? KSClassDeclaration }
                .filter { Modifier.SEALED in it.modifiers }
                .forEach { sealed -> sealed.getSealedSubclasses().forEach { sub -> if (sub.classKind == ClassKind.OBJECT) sealedObjectSubclasses += sub } }
            sealedObjectSubclasses.forEach { obj -> gFun.addStatement("%T::class -> %T", obj.toClassName(), obj.toClassName()) }

            builtins.entries.filter { !it.key.startsWith("java.") }.forEach { (qualifiedName, templateValue) ->
                val (template, value) = templateValue
                // Unlike fakeInitializerOf's use of these same templates (always in a context with a
                // known target type, e.g. a named constructor argument), this `when` branch's target
                // type is just `Any` — none of these generic factories (constructors or top-level
                // `emptyXxx()`/`emptyArray()` functions alike) can infer a type argument there.
                val typeArgArity = when (qualifiedName) {
                    "kotlin.collections.Map", "kotlin.collections.HashMap", "kotlin.collections.LinkedHashMap" -> 2
                    else -> if (template == "%M()") 1 else 0
                }
                val placeholderTemplate =
                    if (typeArgArity > 0) "%M<${List(typeArgArity) { "Any?" }.joinToString(", ")}>()" else template
                val pkg = qualifiedName.substringBeforeLast('.')
                val simple = qualifiedName.substringAfterLast('.')
                gFun.addStatement("%T::class -> $placeholderTemplate", ClassName(pkg, simple), value)
            }

            placeholderArrayTypes.forEach { arrType ->
                val componentType = arrType.arguments.first().type!!.resolve().toTypeName()
                val emptyArray = MemberName("kotlin", "emptyArray")
                // A type literal with an explicit type argument (`Array<String>::class`) is JVM-only
                // syntax — Kotlin/Native's parser rejects it outright. An instance-based class
                // literal (the class of an actual, constructed array) works identically everywhere,
                // and — on the JVM specifically — still resolves to the same component-type-specific
                // KClass that `Array<String>::class` would, since JVM arrays reify their component
                // type regardless of how their class is obtained.
                gFun.addStatement("%M<%T>()::class -> %M<%T>()", emptyArray, componentType, emptyArray, componentType)
            }

            // One branch per KClass, since only the first matching one of a `when` ever runs.
            // Every shape claims the declaration KSP resolved it to, and a suspend shape *also* wants
            // `Function<arity+1>::class` (see below) — a key a genuine, non-suspend shape one arity
            // higher may already own. The genuine shape wins: it is the only value that key can be
            // looked up with anywhere except the JVM, and on the JVM erasure makes either lambda
            // satisfy the cast. Registering the fallbacks in a second pass is what enforces that,
            // whatever order the shapes were discovered in.
            val functionShapeBranches = LinkedHashMap<ClassName, Pair<Boolean, Int>>()
            placeholderFunctionShapes.forEach { (decl, isSuspendAndArity) ->
                // Same declaration KSP itself resolved the type to — same as any other interface's
                // `Bar::class` branch.
                functionShapeBranches[decl.toClassName()] = isSuspendAndArity
            }
            placeholderFunctionShapes.values.forEach { isSuspendAndArity ->
                val (isSuspend, arity) = isSuspendAndArity
                if (isSuspend) {
                    // On the JVM specifically, a reified suspend function type's runtime class is its
                    // CPS-transformed backing type (Function(arity+1), continuation appended), not the
                    // frontend-level SuspendFunctionN declaration KSP resolves above — Native's and
                    // Wasm's own reification, unlike the JVM's, does match the frontend declaration.
                    // Since a suspend-shaped lambda genuinely implements both on the JVM, adding this
                    // second branch covers both platforms' actual runtime lookup key.
                    functionShapeBranches.getOrPut(ClassName("kotlin", "Function${arity + 1}")) { isSuspendAndArity }
                }
            }

            functionShapeBranches.forEach { (branchClass, isSuspendAndArity) ->
                val (isSuspend, arity) = isSuspendAndArity
                val shape = buildString {
                    if (isSuspend) append("suspend ")
                    append("(")
                    append(List(arity) { "Any?" }.joinToString(", "))
                    append(") -> Any?")
                }
                // Explicitly typed: JS/Wasm, unlike JVM/Native, don't infer untyped `_` lambda
                // parameters from the surrounding `as Shape` cast.
                val params = if (arity == 0) "" else List(arity) { "_: Any?" }.joinToString(", ") + " -> "
                val message = "The MocKMP processor could not create a placeholder for this function type."
                // A declared-type local val, not a post-hoc `as` cast: a bare lambda literal is
                // always compiled non-suspend, and casting it afterwards is a genuine (failing) cast
                // for a suspend shape, not a no-op — the lambda has to be compiled *as* the target
                // shape from the start, which only a declared-type context (not `as`) provides.
                val value = "run { val f: $shape = { ${params}error(%S) }; f }"
                gFun.addStatement("%T::class -> $value", branchClass, message)
            }

            gFun.addStatement("else -> error(\"Could not find placeholder for type \$cls\")")
            gFun.endControlFlow()

            gFile.addFunction(gFun.build())
            gFile.build().writeTo(codeGenerator, Dependencies(true))
        }

        // endregion
    }
