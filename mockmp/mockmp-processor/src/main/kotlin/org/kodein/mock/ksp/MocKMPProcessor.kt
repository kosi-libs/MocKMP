        // region Phase 2: transitive fakes

        /**
         * [type] with every reference to one of [vCls]'s type parameters replaced by the matching
         * type argument of [vType] — `GenData<T>` becomes `GenData<String>` when [vType] is
         * `Wrap<String>` — or `null` when one of them belongs to an enclosing declaration rather
         * than to [vCls], which the arguments of [vType] say nothing about.
         *
         * When [vType] projects a type parameter with a star — which is all a `KClass` reference can
         * express, so it is what every `@UsesFakes(Generic::class)` produces — the parameter's first
         * bound stands in for it, the same "good enough" substitute [asBoundedType] uses. An
         * undeclared bound is `Any?`, which is why `NullGenData<T>(val content: T)` fakes its content
         * as `null` while `NonNullGenData<T : Any>` fakes it as an `Any` instance.
         *
         * Substitution is recursive: a type parameter can be nested at any depth (`GenData<GenData<T>>`,
         * `() -> GenData<T>`), and only substituting a *bare* type parameter would leave the rest
         * unresolved — with no `fakeGenDataXTX()` function to call for it.
         *
         * Returns [type] itself when nothing was substituted: [toFake], [fakes] and [providedFakes]
         * are keyed by [KSType], so a rebuilt-but-equivalent instance must never be introduced needlessly.
         */
        private fun substituteTypeParameters(type: KSType, vCls: KSClassDeclaration, vType: KSType): KSType? {
            val decl = type.declaration
            if (decl is KSTypeParameter) {
                val index = vCls.typeParameters.indexOf(decl)
                if (index < 0) return null
                val resolved = vType.arguments.getOrNull(index)?.type?.resolve() ?: decl.boundType()
                // `T?` substitutes to `String?`, not to `String`: dropping the nullability would make
                // constructorParamTypeToFake (which skips nullable parameters) and resolveConstructorArgs
                // (which emits `null` for them) disagree on whether a fake is needed at all.
                return if (type.isMarkedNullable) resolved.makeNullable() else resolved
            }
            if (type.arguments.isEmpty()) return type

            var substituted = false
            val arguments = type.arguments.map { argument ->
                val argumentType = argument.type?.resolve() ?: return@map argument // A star projection has nothing to substitute.
                val resolved = substituteTypeParameters(argumentType, vCls, vType) ?: return null
                if (resolved == argumentType) return@map argument
                substituted = true
                resolver.getTypeArgument(resolver.createKSTypeReferenceFromKSType(resolved), argument.variance)
            }
            return if (substituted) type.replace(arguments) else type
        }

        /**
         * The type a fake has to be generated for, to produce a value of [type] — or `null` when no
         * generation is needed: [type] is nullable (the value is `null`), is a [builtins] type, or
         * already has a fake ([providedFakes] or [toFake]). A function type unwraps to its return
         * type, since its value is a lambda returning a fake of that — and `StateFlow<T>`/
         * `MutableStateFlow<T>` unwraps to `T`, since its value is `MutableStateFlow(<faked T>)`
         * (see [fakeInitializerOf]) — unless [providedFakes] already covers the *whole* `StateFlow<T>`
         * itself, in which case `T` needs no fake of its own either.
         *
         * The discovery-side counterpart of [fakeValueOf], which emits the value itself: the two
         * must agree on which types need a `fakeXxx()` function, or generation would emit a call to
         * a function nothing ever generated.
         */
        private fun valueTypeToFake(type: KSType): KSType? {
            if (type.nullability != Nullability.NOT_NULL) return null
            val valueType = if (type.isAnyFunctionType) type.arguments.last().type!!.resolve() else type
            // Resolved so the result matches the keys addFake/providedFakes actually use (see unwrapAliases).
            val resolvedType = valueType.unwrapAliases()
            if (resolvedType in providedFakes) return null
            val qualifiedName = resolvedType.declaration.qualifiedName?.asString()
            if (qualifiedName == "kotlinx.coroutines.flow.StateFlow" || qualifiedName == "kotlinx.coroutines.flow.MutableStateFlow") {
                return resolvedType.arguments.firstOrNull()?.type?.resolve()?.let { valueTypeToFake(it) }
            }
            return resolvedType.takeIf { qualifiedName !in builtins && it !in toFake }
        }

        /**
         * Resolves the type a fake is needed for, for constructor [param] of fake class [vCls]
         * (whose fake is being generated for [vType]) — or `null` if [param] needs no fake: it has
         * a default value, or [valueTypeToFake] says so.
         */
        private fun constructorParamTypeToFake(vCls: KSClassDeclaration, vType: KSType, param: KSValueParameter, process: ToProcess): KSType? {
            if (param.hasDefault) return null
            // Nullability is tested *after* substitution, as [resolveConstructorArgs] does: a type
            // parameter can substitute to a nullable type, and the two must agree on which
            // parameters get a fake and which are simply set to `null`.
            val paramType = substituteTypeParameters(param.type.resolve(), vCls, vType)
                ?: error(param, "Could not resolve generic parameter $param (${process.references.firstOrNull()?.location})")
            return valueTypeToFake(paramType)
        }

        /**
         * True when a fake of [this] declaration is produced by *implementing* it — a generated
         * `FakeXxx` class (see [addFakeImplementation]) — rather than by calling a constructor.
         *
         * A sealed type is excluded even though it is abstract: it is resolved to a permitted
         * subclass instead (see [resolveSealedTarget]), and could not be extended by a generated
         * class anyway.
         */
        private fun KSClassDeclaration.isFakedByImplementing(): Boolean =
            Modifier.SEALED !in modifiers &&
                    (classKind == ClassKind.INTERFACE || (classKind == ClassKind.CLASS && Modifier.ABSTRACT in modifiers))

        /**
         * Every abstract member of [vType] that a generated implementation has to produce a value
         * for — property types and non-`Unit` function return types alike — resolved as members of
         * [vType] so that a generic type's arguments are substituted in
         * ([KSPropertyDeclaration.asMemberOf]), paired with the declaration to blame if that value
         * turns out to be unfakeable and the requirement-path step it contributes (rendered from the
         * substituted signature, so a generic supertype's arguments show as instantiated). Empty for
         * anything not faked by implementing.
         *
         * Shared by [expandTransitiveFakes], which turns these into `fakeXxx()` functions, and
         * [addFakeImplementation], which emits the calls to them — the two must walk the same
         * members, or generation would emit a call to a function nothing generated.
         *
         * A function returning one of its *own* type parameters is skipped: no value of it can be
         * produced, and [addFakeImplementation] gives it a throwing body rather than a faked one.
         */
        private fun implementedMemberTypes(vType: KSType): List<MemberToFake> {
            val decl = vType.declaration as? KSClassDeclaration ?: return emptyList()
            if (!decl.isFakedByImplementing()) return emptyList()
            val implementedType = vType.withBoundArguments()
            val owner = vType.pathName()
            val propTypes = decl.getAllProperties()
                .filter { it.isAbstract() }
                .map { vProp ->
                    val vPropType = vProp.asMemberOf(implementedType)
                    MemberToFake(vPropType, vProp, propertyPathStep(owner, vProp, vPropType))
                }
            val returnTypes = decl.getAllFunctions()
                .filter { it.isAbstract && it.simpleName.asString() !in IDENTITY_MEMBERS }
                .map { vFun -> vFun to vFun.asMemberOf(implementedType) }
                .filter { (_, vFunSig) -> vFunSig.returnType?.let { !it.isUnit() && !it.mentionsTypeParameter() } == true }
                .map { (vFun, vFunSig) ->
                    val vReturnType = vFunSig.returnType!!
                    MemberToFake(vReturnType, vFun, functionPathStep(owner, vFun, vFunSig.parameterTypes, vReturnType))
                }
            return (propTypes + returnTypes).toList()
        }

        /**
         * Breadth-first expansion of [toFake]: a fake may itself require fakes for its own
         * constructor parameter types (a `data class Foo(val bar: Bar)` needs `fakeBar()` too), or —
         * when it is faked by implementing an interface or an abstract class — for its abstract
         * member types (see [implementedMemberTypes]), so this walks both graphs and adds any type
         * not already covered. Every [toFake] entry is requested directly (`@Fake`/`@UsesFakes`/a
         * `@Fake`-annotated property) or reached from one by this very walk — a mocked interface's own
         * members are never a seed here; see [Round.seedPlaceholder]/[Round.expandTransitivePlaceholders]
         * for that graph instead. Discovered types inherit their parent's [ToProcess.implicit] flag —
         * always `false` here, since nothing that starts this walk is implicit — and their parent's
         * [ToProcess.origin], unchanged; only [ToProcess.path] grows a step at each hop.
         */
        private fun expandTransitiveFakes() {
            val toExplore = ArrayDeque(toFake.map { it.toPair() })
            while (toExplore.isNotEmpty()) {
                val (type, process) = toExplore.removeFirst()
                // The constructor that will be called is the sealed target's, not the sealed parent's
                // (which isn't even public) — the two phases must walk the same one.
                val targetType = resolveSealedTargetType(type)
                val cls = targetType.declaration as KSClassDeclaration
                // Every discovered type is enqueued with *its own* entry, not its parent's: the two
                // differ by exactly the requirement path, which is what the child must explore under.
                cls.firstPublicConstructor()?.let { vCstr ->
                    val path = process.path + constructorPathStep(targetType.pathName(), vCstr)
                    vCstr.parameters.forEach { param ->
                        val paramTypeToFake = constructorParamTypeToFake(cls, targetType, param, process) ?: return@forEach
                        addFake(paramTypeToFake, process.files, param, origin = process.origin, implicit = process.implicit, path = path)
                        toExplore.add(paramTypeToFake to toFake.getValue(paramTypeToFake))
                    }
                }
                implementedMemberTypes(targetType).forEach { member ->
                    val memberTypeToFake = valueTypeToFake(member.type) ?: return@forEach
                    addFake(memberTypeToFake, process.files, member.node, origin = process.origin, implicit = process.implicit, path = process.path + member.step)
                    toExplore.add(memberTypeToFake to toFake.getValue(memberTypeToFake))
                }
            }
        }

        // endregion

        // region Phase 2.5: transitive placeholders

        /**
         * The placeholder counterpart of [valueTypeToFake]: the type a placeholder has to be
         * generated for, to produce a value of [type] — or `null` when none is needed, because
         * [valueTypeToFake] already says so (nullable, a [builtins] type, a `@FakeProvider`, or
         * already in [toFake] — every one of those is resolved through the Fake path instead, see
         * [Round.fakeInitializerOf]'s placeholder mode), or because [type]'s declaration is already in
         * [toMock] (resolved through the Mock path instead, same place).
         */
        private fun valueTypeToPlaceholder(type: KSType): KSType? {
            val resolvedType = valueTypeToFake(type) ?: return null
            val decl = resolvedType.declaration
            if (decl !is KSClassDeclaration) return null
            // Same reasoning as seedPlaceholder's identical check: an error-type declaration passes
            // `is KSClassDeclaration`, but has no qualifiedName to derive a placeholderXxx() name from
            // — registering it as its own Placeholder target would only fail later, in exactly the
            // way this processor already handles: fakeInitializerOf(asPlaceholder = true) throws for
            // it at the call site that actually needs its value ([expandTransitivePlaceholders]'s own
            // caller, one level up), degrading *that* placeholder to a throwing stub instead.
            if (decl.qualifiedName == null) return null
            return resolvedType.takeIf { decl !in toMock }
        }

        /**
         * The placeholder counterpart of [constructorParamTypeToFake]: resolves the type a placeholder
         * is needed for, for constructor [param] of class [vCls] (whose placeholder is being generated
         * for [vType]) — or `null` if [param] needs no placeholder: it has a default value, or
         * [valueTypeToPlaceholder] says so.
         */
        private fun constructorParamTypeToPlaceholder(vCls: KSClassDeclaration, vType: KSType, param: KSValueParameter, process: ToProcess): KSType? {
            if (param.hasDefault) return null
            val paramType = substituteTypeParameters(param.type.resolve(), vCls, vType)
                ?: error(param, "Could not resolve generic parameter $param (${process.references.firstOrNull()?.location})")
            return valueTypeToPlaceholder(paramType)
        }

        /**
         * Breadth-first expansion of [toPlaceholder]: a placeholder may itself require placeholders
         * for its own constructor parameter types, exactly as [expandTransitiveFakes] walks a fake's —
         * but never for abstract member types, which is the one thing that keeps a placeholder from
         * growing into a full fake (see [toPlaceholder]'s own doc). Also seeds from [toMock]'s
         * abstract-*class* entries — unlike [expandTransitiveFakes]'s old, removed equivalent, this
         * deliberately excludes mocked *interfaces*, which have no superclass constructor call to
         * satisfy — for [addSuperclassConstructorArgs]' sake. Discovered types are always implicit:
         * nothing that reaches [toPlaceholder] was requested directly.
         *
         * Each discovered entry is keyed and explored by the precise, already-substituted
         * `paramType` [constructorParamTypeToPlaceholder] returns — never re-bounded — the same
         * "keep the exact instantiation" reasoning [toPlaceholder]'s own doc gives for a Placeholder
         * over a Mock. An abstract-mock seed still explores from [KSClassDeclaration.asBoundedType],
         * having no more precise instantiation available. This now carries the same self-growing-
         * generic non-termination hazard [expandTransitiveFakes] already does (a constructor
         * parameter whose type is a strictly larger instantiation of its own enclosing type).
         */
        private fun expandTransitivePlaceholders() {
            val abstractMockSeeds = toMock.entries
                .filter { (decl, _) -> decl.classKind == ClassKind.CLASS && Modifier.ABSTRACT in decl.modifiers }
                .map { (decl, process) -> decl.asBoundedType() to process }
            val toExplore = ArrayDeque(toPlaceholder.map { it.toPair() } + abstractMockSeeds)
            while (toExplore.isNotEmpty()) {
                val (type, process) = toExplore.removeFirst()
                val targetType = resolveSealedTargetType(type)
                val cls = targetType.declaration as? KSClassDeclaration ?: continue
                val vCstr = cls.firstPublicConstructor() ?: continue
                val path = process.path + constructorPathStep(targetType.pathName(), vCstr)
                vCstr.parameters.forEach { param ->
                    val paramType = constructorParamTypeToPlaceholder(cls, targetType, param, process) ?: return@forEach
                    val childProcess = toPlaceholder.getOrPut(paramType) {
                        ToProcess().apply { this.origin = process.origin; implicit = true; this.path = path }
                    }
                    childProcess.files.addAll(process.files)
                    childProcess.references.add(param)
                    toExplore.add(paramType to childProcess)
                }
            }
        }

        // endregion

        // region Phase 3: mock generation

        /**
         * Appends `: SuperClass(arg1, arg2, ...)` superclass constructor arguments to [gCls] for
         * abstract class [vCls]'s primary constructor, as instantiated by [vType] and resolved the
         * same way fake-class constructor arguments are (see [resolveConstructorArgs]) — the
         * generated instance still has to satisfy its supertype's real constructor. [asPlaceholder]
         * distinguishes the two callers: `false` for a faked abstract class ([addFakeImplementation]),
         * `true` for a *mocked* one ([mockClassBuilder]) — its superclass constructor's own
         * dependencies are placeholders (see [expandTransitivePlaceholders]'s abstract-class seeds),
         * never a redundant fake generated solely to feed this one call.
         */
        private fun addSuperclassConstructorArgs(gCls: TypeSpec.Builder, vCls: KSClassDeclaration, vType: KSType, filesDeps: MutableSet<KSFile>, asPlaceholder: Boolean = false) {
            val vCstr = vCls.firstPublicConstructor() ?: return
            resolveConstructorArgs(vCls, vCstr, vType, filesDeps, asPlaceholder).forEach { (format, values) ->
                gCls.addSuperclassConstructorParameter(format, *values.toTypedArray())
            }
        }

        /**
         * `kotlin.SubclassOptInRequired`'s marker classes on [this] declaration, if any — the
         * annotation placed on an interface/abstract class (e.g. kotlinx.serialization's
         * `SerialDescriptor`, itself annotated `@SubclassOptInRequired(SealedSerializationApi::class)`)
         * that makes extending or implementing it require an explicit opt-in ("This class or interface
         * should not be inherited/implemented outside of kotlinx.serialization library. Note it is
         * still permitted to use it directly."). Empty when [this] carries none — the overwhelmingly
         * common case.
         *
         * `(anno.arguments.first().value as List<*>)` reads a `vararg _: KClass<*>` annotation
         * argument — the same shape `@UsesFakes`/`@UsesMocks` have, and the same code [lookUpUses]
         * already uses to read those.
         */
        private fun KSClassDeclaration.subclassOptInMarkers(): List<KSType> =
            annotations
                .filter { it.annotationType.resolve().declaration.qualifiedName?.asString() == "kotlin.SubclassOptInRequired" }
                .flatMap { anno -> (anno.arguments.firstOrNull()?.value as? List<*>)?.filterIsInstance<KSType>() ?: emptyList() }
                .toList()

        /**
         * Every `kotlin.RequiresOptIn`-marked annotation applying to [this] declaration — directly,
         * or via one of its lexical ancestors (walking [KSDeclaration.parentDeclaration]), since
         * Kotlin's opt-in contagion propagates through lexical scope: kotlinx.serialization's
         * `PolymorphicKind.OPEN` carries no annotation of its own, but its enclosing `PolymorphicKind`
         * is `@ExperimentalSerializationApi`, and referencing `OPEN` needs the same opt-in referencing
         * `PolymorphicKind` itself would.
         *
         * Distinct from [subclassOptInMarkers]: this fires for *any* mention of [this] declaration
         * (a return type, a referenced object/enum entry, a `::class` literal) — not only when it is
         * being subclassed — which is why every call site below checks both, on whichever declarations
         * it actually references.
         */
        private fun KSDeclaration.requiredOptInMarkers(): List<KSType> {
            val markers = LinkedHashSet<KSType>()
            var decl: KSDeclaration? = this
            while (decl != null) {
                decl.annotations.forEach { anno ->
                    val markerType = anno.annotationType.resolve()
                    val markerDecl = markerType.declaration as? KSClassDeclaration
                    if (markerDecl != null && markerDecl.annotations.any {
                            it.annotationType.resolve().declaration.qualifiedName?.asString() == "kotlin.RequiresOptIn"
                        }) markers += markerType
                }
                decl = decl.parentDeclaration
            }
            return markers.toList()
        }

        /** `@OptIn(Marker1::class, Marker2::class)` for the union of [markers], or `null` if empty. */
        private fun optInAnnotation(markers: Collection<KSType>): AnnotationSpec? {
            if (markers.isEmpty()) return null
            val gAnno = AnnotationSpec.builder(ClassName("kotlin", "OptIn"))
            markers.forEach { marker -> gAnno.addMember("%T::class", marker.toTypeName()) }
            return gAnno.build()
        }

        /**
         * Appends `@OptIn(Marker1::class, Marker2::class)` to [gCls] for the union of [this]
         * declaration's [subclassOptInMarkers] and [requiredOptInMarkers] — required for a generated
         * `MockXxx`/`FakeXxx`/`PlaceholderXxx` to legally implement or extend a type like
         * `SerialDescriptor` ([subclassOptInMarkers]), or a type that is itself `@RequiresOptIn`-marked
         * ([requiredOptInMarkers] — the generated class's own declaration mentions it, via its
         * supertype). Only the *exact* type about to be subclassed needs checking, not its whole
         * ancestor chain: opt-in propagation stops at whichever supertype already satisfied it, and if
         * that satisfaction was itself a re-declaration (propagating further), it shows up again right
         * there on that same declaration — never further down without also being redeclared.
         *
         * Emits `@OptIn`, not a re-declared marker: nothing is ever meant to subclass a generated
         * implementation further, so the non-propagating form is both sufficient and the narrower,
         * correct choice. `@OptIn` has `SOURCE` retention, so it only has to be present in this
         * generated file — which it is.
         */
        private fun KSClassDeclaration.addOptInAnnotation(gCls: TypeSpec.Builder) {
            optInAnnotation((subclassOptInMarkers() + requiredOptInMarkers()).distinct())?.let { gCls.addAnnotation(it) }
        }

        /**
         * `MockXxx(Mocker())` for [decl] — the expression every "use the existing Mock" branch needs,
         * shared by [fakeInitializerOf]'s placeholder mode and [generatePlaceholderAccessor]. Builds
         * the class name by the same convention [generateMockClass] used to generate it
         * ([KSDeclaration.fakePackageName], [KSDeclaration.toMockName]) rather than reading it back
         * from [mocks] — [fakeInitializerOf] can run before every mock has been generated (a mocked
         * abstract class's own superclass constructor argument may itself be a *different* mocked
         * type, generated later in [toMock]'s iteration order), so the name has to be computable
         * without waiting on that map, exactly as [addMockInjection] already does for the same reason.
         *
         * [type], when given, is the exact instantiation the caller needs a `MockXxx` *of* — a
         * placeholder's constructor argument typed `Foo<Bar>` needs a `MockFoo<Bar>`, not a
         * `MockFoo<Any>`: `Foo` being declared `out T : Any` makes the latter not even a subtype of
         * the former, so the bounded fallback below would generate code that fails to typecheck.
         * Falls back to each parameter's own bound — the same "good enough" stand-in
         * [KSClassDeclaration.asBoundedType] uses — when there is no [type] to instantiate at
         * ([generatePlaceholderAccessor]'s call site, whose target is the erased `Any` a `KClass`
         * dispatch works with) or its argument count doesn't match [decl]'s own parameters.
         */
        private fun mockConstructorCall(decl: KSClassDeclaration, type: KSType? = null): Pair<String, List<Any>> {
            val mockClassName = ClassName(decl.fakePackageName(), decl.toMockName())
            val mockTypeName: TypeName = when {
                decl.typeParameters.isEmpty() -> mockClassName
                type != null && type.arguments.size == decl.typeParameters.size ->
                    mockClassName.parameterizedBy(*type.withBoundArguments().arguments.map { it.type!!.resolve().toTypeName() }.toTypedArray())
                else -> mockClassName.parameterizedBy(*decl.typeParameters.map { it.bounds.first().resolve().toTypeName() }.toTypedArray())
            }
            return "%T(%T())" to listOf(mockTypeName, mockerTypeName)
        }

        /**
         * Builds the `MockXxx` class shell for [vItf]: supertype (interface or abstract class),
         * type variables, and the private `mocker` constructor property. Its `init` block registers
         * [providePlaceholder] on that `mocker` — this is what makes the placeholder provider
         * reliably available by the time any `isAny()`/`isEqual()`/etc. call could need it, since
         * you cannot obtain a mock instance without going through this constructor first.
         */
        private fun mockClassBuilder(vItf: KSClassDeclaration, mockClassName: String, filesDeps: MutableSet<KSFile>): Pair<TypeSpec.Builder, PropertySpec> {
            val gCls = TypeSpec.classBuilder(mockClassName)
                .addModifiers(visibilityModifier)
            vItf.addOptInAnnotation(gCls)
            val superType =
                if (vItf.typeParameters.isEmpty()) vItf.toClassName()
                else vItf.toClassName().parameterizedBy(vItf.typeParameters.map { it.toTypeVariableName() })
            if (vItf.classKind == ClassKind.INTERFACE) {
                gCls.addSuperinterface(superType)
            } else {
                gCls.superclass(superType)
                addSuperclassConstructorArgs(gCls, vItf, vItf.asBoundedType(), filesDeps, asPlaceholder = true)
            }
            vItf.typeParameters.forEach { vParam -> gCls.addTypeVariable(vParam.toTypeVariableName()) }
            gCls.primaryConstructor(
                FunSpec.constructorBuilder()
                    .addParameter("mocker", mockerTypeName)
                    .build()
            )
            val mocker = PropertySpec.builder("mocker", mockerTypeName)
                .initializer("mocker")
                .addModifiers(KModifier.PRIVATE)
                .build()
            gCls.addProperty(mocker)
            gCls.addInitializerBlock(
                CodeBlock.of("mocker.registerPlaceholderProvider(::%M)\n", MemberName(accessorsPackage, "providePlaceholder"))
            )
            return gCls to mocker
        }

        /**
         * The [org.kodein.mock.Mocker]-backed override for one abstract property of the mocked
         * interface, e.g. for `val bar: String` and mutable `var baz: Int`:
         *
         * ```
         * override val bar: String get() = this.mocker.register(this, "get:bar")
         * override var baz: Int
         *     get() = this.mocker.register(this, "get:baz")
         *     set(value) { this.mocker.register(this, "set:baz", value) }
         * ```
         */
        private fun mockedProperty(vProp: KSPropertyDeclaration, vItf: KSClassDeclaration, mocker: PropertySpec): PropertySpec {
            val typeParamResolver = vProp.typeParameters.toTypeParameterResolver(vItf.typeParameters.toTypeParameterResolver())
            val gPropType = vProp.type.toTypeName(typeParamResolver)
            val gProp = PropertySpec.builder(vProp.simpleName.asString(), gPropType)
                .addModifiers(KModifier.OVERRIDE)
                .getter(
                    FunSpec.getterBuilder()
                        .addStatement("return this.%N.register(this, %S)", mocker, "get:${vProp.simpleName.asString()}")
                        .build()
                )
            gProp.addAnnotations(vProp.overrideAnnotations())
            if (vProp.isMutable) {
                gProp.mutable(true)
                    .setter(
                        FunSpec.setterBuilder()
                            .addParameter("value", gPropType)
                            .addStatement("return this.%N.register(this, %S, value)", mocker, "set:${vProp.simpleName.asString()}")
                            .build()
                    )
            }
            return gProp.build()
        }

        /**
         * The `"name(kotlin.Int, vararg kotlin.String)"` key computed for [vFun] — the same key
         * [org.kodein.mock.Mocker.register]/`registerSuspend` receive as `method`, and that
         * `every { }` blocks match recorded calls against.
         */
        private fun registrationKey(vFun: KSFunctionDeclaration): String {
            val paramsDescription = vFun.parameters.joinToString {
                (it.type.resolve().declaration as? KSClassDeclaration)?.qualifiedName?.asString()?.let { str ->
                    if (it.isVararg) "vararg $str" else str
                } ?: "?"
            }
            return "${vFun.simpleName.asString()}($paramsDescription)"
        }

        /**
         * Appends an *identity* override of [vFun] — one of [IDENTITY_MEMBERS] — to [gCls], for the
         * case where [vItf] re-declares it as abstract and Kotlin therefore requires an
         * implementation. Routing it through the mocker is what this exists to avoid.
         *
         * A mocked interface can defer to `Any`'s own implementations, since `super` resolves past
         * the interface to `Any`:
         *
         * ```
         * override fun equals(other: Any?): Boolean = super.equals(other)
         * ```
         *
         * A mocked *abstract class* cannot — `super` resolves to the class itself, where the member
         * is abstract ("Abstract member cannot be accessed directly") — so identity is spelled out,
         * with a per-instance hash since Kotlin has no common-source identity hash:
         *
         * ```
         * private val identityHashCode: Int = Random.nextInt()
         * override fun equals(other: Any?): Boolean = this === other
         * override fun hashCode(): Int = identityHashCode
         * ```
         */
        private fun addIdentityOverride(gCls: TypeSpec.Builder, vFun: KSFunctionDeclaration, vItf: KSClassDeclaration) {
            val canCallSuper = vItf.classKind == ClassKind.INTERFACE
            when (vFun.simpleName.asString()) {
                "equals" -> gCls.addFunction(
                    FunSpec.builder("equals")
                        .addModifiers(KModifier.OVERRIDE)
                        .addParameter("other", ANY.copy(nullable = true))
                        .returns(BOOLEAN)
                        .addStatement(if (canCallSuper) "return super.equals(other)" else "return this === other")
                        .build()
                )
                "hashCode" -> {
                    if (!canCallSuper) {
                        gCls.addProperty(
                            PropertySpec.builder("identityHashCode", INT, KModifier.PRIVATE)
                                .initializer("%T.nextInt()", ClassName("kotlin.random", "Random"))
                                .build()
                        )
                    }
                    gCls.addFunction(
                        FunSpec.builder("hashCode")
                            .addModifiers(KModifier.OVERRIDE)
                            .returns(INT)
                            .addStatement(if (canCallSuper) "return super.hashCode()" else "return identityHashCode")
                            .build()
                    )
                }
            }
        }

        /** True when [this] member carries `kotlin.Deprecated`. */
        private fun KSDeclaration.isDeprecated(): Boolean =
            annotations.any { it.annotationType.resolve().declaration.qualifiedName?.asString() == ANNOTATION_DEPRECATED }

        /**
         * The annotations of [this] mocked member, as they should appear on the generated override.
         *
         * `kotlin.Deprecated` is dropped. It is never *required* on an override — omitting it only
         * warns on the override itself, which [generateMockClass] suppresses — whereas propagating it
         * warns at every call the test makes to the mock, about the interface being deprecated rather
         * than about anything the test did.
         *
         * Everything else is kept, deliberately: an override must repeat its supertype's opt-in
         * markers, and compiler-plugin annotations that change the calling convention (`@Composable`
         * above all) must be repeated or the override will not compile at all.
         *
         * `omitDefaultValues` keeps the copy faithful — without it `@Deprecated("…")` came out
         * carrying a materialised `ReplaceWith(expression = "")`.
         */
        private fun KSDeclaration.overrideAnnotations(): List<AnnotationSpec> =
            annotations
                .filter { it.annotationType.resolve().declaration.qualifiedName?.asString() != ANNOTATION_DEPRECATED }
                .map { it.toAnnotationSpec(omitDefaultValues = true) }
                .toList()

        /**
         * The [org.kodein.mock.Mocker]-backed override for one function of the mocked interface,
         * e.g. for `fun baz(i: Int): String`:
         *
         * ```
         * override fun baz(i: Int): String = this.mocker.register(this, "baz(kotlin.Int)", i)
         * ```
         *
         * Non-abstract (default) interface members get a `default = { super.baz(i) }` fallback, so
         * that mocking them with `every { }` remains optional.
         */
        private fun mockedFunction(vFun: KSFunctionDeclaration, vItf: KSClassDeclaration, mocker: PropertySpec): FunSpec {
            val gFun = FunSpec.builder(vFun.simpleName.asString())
                .addModifiers(KModifier.OVERRIDE)
            val typeParamResolver = vFun.typeParameters.toTypeParameterResolver(vItf.typeParameters.toTypeParameterResolver())
            vFun.typeParameters.forEach { vParam -> gFun.addTypeVariable(vParam.toTypeVariableName(typeParamResolver)) }
            gFun.addModifiers((vFun.modifiers - Modifier.ABSTRACT - Modifier.OPEN - Modifier.OPERATOR).mapNotNull { it.toKModifier() })
            gFun.returns(vFun.returnType!!.toTypeName(typeParamResolver))
            gFun.addAnnotations(vFun.overrideAnnotations())
            vFun.parameters.forEach { vParam ->
                gFun.addParameter(vParam.name!!.asString(), vParam.type.toTypeName(typeParamResolver), if (vParam.isVararg) listOf(KModifier.VARARG) else emptyList())
            }
            val paramsCall = if (vFun.parameters.isEmpty()) "" else vFun.parameters.joinToString { it.name!!.asString() }
            val register = if (Modifier.SUSPEND in vFun.modifiers) "registerSuspend" else "register"
            val default = if (vFun.isAbstract) "" else "default = { super.${vFun.simpleName.asString()}($paramsCall) }"
            gFun.addStatement(
                "return this.%N.$register(this, %S${paramsCall.withNonEmptyPrefix(", ")}${default.withNonEmptyPrefix(", ")})",
                mocker,
                registrationKey(vFun)
            )
            return gFun.build()
        }

        /**
         * Generates the `MockXxx` class implementing interface (or, for an abstract class, extending
         * it) [vItf], into its own file, e.g. for
         * `interface Foo { val bar: String; fun baz(i: Int): String }`:
         *
         * ```
         * internal class MockFoo(mocker: Mocker) : Foo {
         *     private val mocker: Mocker = mocker
         *     override val bar: String get() = this.mocker.register(this, "get:bar")
         *     override fun baz(i: Int): String = this.mocker.register(this, "baz(kotlin.Int)", i)
         * }
         * ```
         *
         * A [toMock] entry is always explicit — a mock is never discovered transitively — so, for an
         * interface, every member is overridden: abstract members through the mocker, non-abstract
         * (default) ones with a `default = { super.foo() }` fallback so mocking them remains optional.
         * An abstract class only ever has abstract members overridden — mirroring the "abstract only"
         * rule a faked abstract class follows too ([addFakeImplementation]) — since a default method
         * has no meaning there; and JDK interop default methods like `Iterable.forEach(Consumer)` have
         * repeatedly proven to carry variance that only conflicts when re-declared as an explicit
         * override.
         *
         * Generated into [KSDeclaration.fakePackageName] rather than [vItf]'s own package: besides
         * the same Kotlin-stdlib/JDK write restriction fakes already redirect around, some
         * interfaces (`kotlin.Function1` and friends) live directly in the bare `kotlin` package,
         * which only the standard library itself is allowed to contribute to.
         *
         * Records the generated class name into [mocks], consumed by [generateMockAccessor].
         */
        private fun generateMockClass(vItf: KSClassDeclaration, process: ToProcess) {
            val mockClassName = vItf.toMockName()
            val mockPkg = vItf.fakePackageName()
            val gFile = FileSpec.builder(mockPkg, mockClassName)
            val filesDeps = LinkedHashSet(process.files)
            // Unlike a Fake or a Placeholder, a Mock has no throwing-stub fallback to degrade to: it
            // implements vItf's actual superclass constructor call ([mockClassBuilder]), which every
            // toMock entry is explicit for (see toMock's own doc) — so an UnresolvedTypeError here
            // always aborts the round, the same way any other unfakeable superclass dependency would.
            val (gCls, mocker) = try {
                mockClassBuilder(vItf, mockClassName, filesDeps)
            } catch (e: UnresolvedTypeError) {
                val path = if (process.path.isEmpty()) "" else "\nRequired by: ${process.path.joinToString(" -> ")}"
                error(vItf, "Cannot generate a mock for ${vItf.displayName()} because ${e.message}.$path")
            }
            requirementComment(process)?.let { gCls.addKdoc(it) }
            // Every toMock entry is explicit now — a mock is never discovered transitively — so every
            // interface's non-abstract (default) members are always overridden too, matching an
            // abstract class's own always-abstract-only rule (a default method has no meaning there).
            val overrideAll = vItf.classKind == ClassKind.INTERFACE

            val vProps = vItf.getAllProperties().filter { it.isAbstract() }.toList()
            val vFuns = vItf.getAllFunctions().filter { overrideAll || it.isAbstract }.toList()

            // [overrideAnnotations] drops `kotlin.Deprecated`, which leaves the override warning that
            // it does not repeat its supertype's deprecation. That is the point — the alternative
            // warns in the user's tests instead — so it is silenced here rather than propagated.
            if (vProps.any { it.isDeprecated() } || vFuns.any { it.isDeprecated() }) {
                gCls.addAnnotation(
                    AnnotationSpec.builder(Suppress::class).addMember("%S", "OVERRIDE_DEPRECATION").build()
                )
            }

            vProps.forEach { vProp -> gCls.addProperty(mockedProperty(vProp, vItf, mocker)) }

            vFuns
                .forEach { vFun ->
                    // A supertype that re-declares equals/hashCode as abstract forces an override,
                    // so skipping them outright would not compile — they get an identity
                    // implementation instead of a mocked one (see [addIdentityOverride]).
                    if (vFun.simpleName.asString() in IDENTITY_MEMBERS) {
                        if (vFun.isAbstract) addIdentityOverride(gCls, vFun, vItf)
                    } else {
                        gCls.addFunction(mockedFunction(vFun, vItf, mocker))
                    }
                }

            gFile.addType(gCls.build().also { mocks[vItf] = ClassName(mockPkg, it.name!!) })
            writeWithRequirementComment(gFile, Dependencies(true, *filesDeps.toTypedArray()))
        }

