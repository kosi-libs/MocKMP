        // region Phase 6: accessors

        /**
         * A [FunSpec.Builder] for accessor function [name], with [visibilityModifier] applied and,
         * in multiplatform projects, `actual` — matching the `expect` declaration generated by the
         * MocKMP Gradle plugin (see `mockmp-gradle-plugin/src/main/resources/mockmp.multi.kt`).
         */
        private fun accessorFunBuilder(name: String): FunSpec.Builder {
            val gFun = FunSpec.builder(name).addModifiers(visibilityModifier)
            if (multiplatform) gFun.addModifiers(KModifier.ACTUAL)
            return gFun
        }

        /**
         * Generates the `Mocker.mock(KClass<T>): T` dispatcher, with one `when` branch per
         * *explicitly*-mocked interface — `@Mock`/`@UsesMocks`, filtered by [ToProcess.path] being
         * empty:
         *
         * ```
         * internal actual fun <T : Any> Mocker.mock(type: KClass<T>): T = when (type) {
         *     Foo::class -> MockFoo(this) as T
         *     else -> error("Could not find mock for type $type")
         * }
         * ```
         *
         * The filter is a no-op today — nothing writes [toMock] except [addMock], called only from
         * `@Mock`/`@UsesMocks` sites, so every entry already has an empty [ToProcess.path] — but it is
         * applied the same way [generateFakeAccessor] applies it to [fakes], for the same reason: a
         * mock is only ever meant to be reachable through `mock<T>()` if something requested it
         * directly, and this keeps that true by construction rather than by a coincidence of what else
         * happens not to write [toMock].
         */
        private fun generateMockAccessor() {
            @Suppress("LocalVariableName")
            val T = TypeVariableName("T", Any::class)
            val gFile = FileSpec.builder(accessorsPackage, "mocks")
            val gFun = accessorFunBuilder("mock")
                .receiver(mockerTypeName)
                .addParameter("type", KClass::class.asTypeName().parameterizedBy(T))
                .addTypeVariable(T)
                .returns(T)

            val explicitMocks = mocks.filterKeys { itf -> toMock.getValue(itf).path.isEmpty() }
            if (explicitMocks.isNotEmpty()) {
                gFun.addAnnotation(AnnotationSpec.builder(Suppress::class).addMember("%S", "UNCHECKED_CAST").build())
                gFun.beginControlFlow("return when (type)")
                explicitMocks.forEach { (itf, mock) ->
                    val mockTypeName: TypeName =
                        if (itf.typeParameters.isNotEmpty()) {
                            mock.parameterizedBy(*itf.typeParameters.map { it.bounds.first().resolve().toTypeName() }.toTypedArray())
                        } else {
                            mock
                        }
                    gFun.addStatement("%T::class -> %T(this) as T", itf.toClassName(), mockTypeName)
                }
                gFun.addStatement("else -> error(\"Could not find mock for type \$type\")")
                gFun.endControlFlow()
                optInAnnotation(explicitMocks.keys.flatMap { it.requiredOptInMarkers() }.distinct())?.let { gFun.addAnnotation(it) }
            } else {
                gFun.addStatement("error(\"No mocks declared\")")
            }

            gFile.addFunction(gFun.build())
            write(gFile, Dependencies(true))
        }

        /**
         * Generates the `fake(KType): T` dispatcher, with one `when` branch per *explicitly*-faked
         * type — `@Fake`/`@UsesFakes`/a `@Fake` property, filtered by [ToProcess.path] being empty —
         * keyed by a generated `private val type_pkg_Xxx: KType = typeOf<Xxx>()` (faked types can be
         * generic, and `KType` equality — unlike [KClass] — accounts for type arguments). The
         * package is folded into the name (via [toFunName]) because every one of these properties
         * lives in the same generated `fakes.kt` file, where a bare simple name is not unique
         * (`foo.Data` and `bar.Data` would otherwise both want `type_Data`):
         *
         * ```
         * private val type_foo_Foo: KType = typeOf<foo.Foo>()
         * internal actual fun <T : Any> fake(type: KType): T = when (type) {
         *     type_foo_Foo -> fakefoo_Foo() as T
         *     else -> error("Could not find fake for type $type")
         * }
         * ```
         *
         * A type reached only *transitively* — a constructor parameter or abstract member of another
         * explicitly-faked type (see [expandTransitiveFakes]) — still gets its own `fakeXxx()`
         * function (referenced by whatever needed it, and still a candidate in
         * [generatePlaceholderAccessor]'s Fake-priority branch), but is deliberately left out of this
         * dispatcher: it exists only to satisfy whatever reached it, so if that type's shape changes
         * tomorrow the transitive fake may change or disappear with it. Reaching it through `fake<T>()`
         * directly would make that an unrelated test's runtime failure instead of a compile error at
         * the type that actually needs declaring — `@UsesFakes` (or a `@Fake` property) it yourself if
         * you need it directly.
         */
        private fun generateFakeAccessor() {
            @Suppress("LocalVariableName")
            val T = TypeVariableName("T", Any::class)
            val gFile = FileSpec.builder(accessorsPackage, "fakes")
            val explicitFakes = fakes.filterKeys { type -> toFake.getValue(type).path.isEmpty() }
            explicitFakes.forEach { (type, _) ->
                val gProp = PropertySpec.builder("type_${type.toFunName()}", KType::class)
                    .addModifiers(KModifier.PRIVATE)
                    .initializer("%M<%T>()", MemberName("kotlin.reflect", "typeOf"), type.toTypeName())
                // typeOf<MarkedClass>() mentions MarkedClass right here, in this property's own
                // initializer — a separate declaration from the fake(KType) function below, so its
                // own opt-in requirement (if any) has to be satisfied on the property itself, not on
                // the function that merely refers to the property by name.
                (type.declaration as? KSClassDeclaration)?.let { decl ->
                    optInAnnotation(decl.requiredOptInMarkers())?.let { gProp.addAnnotation(it) }
                }
                gFile.addProperty(gProp.build())
            }
            val gFun = accessorFunBuilder("fake")
                .addAnnotation(AnnotationSpec.builder(Suppress::class).addMember("%S", "UNCHECKED_CAST").build())
                .addParameter("type", KType::class.asTypeName())
                .addTypeVariable(T)
                .returns(T)

            if (explicitFakes.isNotEmpty()) {
                gFun.beginControlFlow("return when (type)")
                explicitFakes.forEach { (type, fake) -> gFun.addStatement("type_${type.toFunName()} -> %M() as T", fake) }
                gFun.addStatement(
                    "else -> error(\"Could not find fake for type \$type. If it exists only as a transitive dependency of " +
                            "another fake, declare it directly with @UsesFakes (or a @Fake property) to make it accessible.\")"
                )
                gFun.endControlFlow()
                // An explicitly-requested type could itself be @RequiresOptIn-marked; not hit by any
                // known case today, but the same mechanism generatePlaceholderAccessor needs for
                // sealedObjectSubclasses, applied here for consistency.
                optInAnnotation(explicitFakes.keys.mapNotNull { it.declaration as? KSClassDeclaration }.flatMap { it.requiredOptInMarkers() }.distinct())
                    ?.let { gFun.addAnnotation(it) }
            } else {
                gFun.addStatement("error(\"No fakes declared\")")
            }
            gFile.addFunction(gFun.build())
            write(gFile, Dependencies(true))
        }

        /**
         * Generates the `Mocker.injectMocks(receiver: Any)` dispatcher, with one `when` branch per
         * class that has injected properties:
         *
         * ```
         * internal actual fun Mocker.injectMocks(receiver: Any) = when (receiver) {
         *     is SomeTests -> injectMocks(receiver)
         *     else -> error("Could not find injector for $receiver")
         * }
         * ```
         *
         * Only the first matching branch of a `when` ever runs, so branches are ordered most derived
         * first: a class always has strictly more supertypes than any of its own supertypes, which
         * makes "supertype count, descending" a valid topological order. Unrelated classes are then
         * ordered by qualified name, so the generated file does not depend on [toInject]'s hash order.
         */
        private fun generateInjectorAccessor() {
            val gFile = FileSpec.builder(accessorsPackage, "injectors")
            val gFun = accessorFunBuilder("injectMocks")
                .receiver(mockerTypeName)
                .addParameter("receiver", Any::class)

            if (toInject.isNotEmpty()) {
                val sorted = toInject.keys.sortedWith(
                    compareByDescending<KSClassDeclaration> { it.getAllSuperTypes().count() }
                        .thenBy { it.qualifiedName?.asString() ?: it.simpleName.asString() }
                )
                gFun.beginControlFlow("return when (receiver)")
                sorted.forEach { cls -> gFun.addStatement("is %T -> %M(receiver)", cls.toClassName(), MemberName(cls.packageName.asString(), "injectMocks")) }
                gFun.addStatement("else -> error(\"Could not find injector for \$receiver\")")
                gFun.endControlFlow()
            } else {
                gFun.addStatement("error(\"No injectors declared\")")
            }
            gFile.addFunction(gFun.build())
            write(gFile, Dependencies(true))
        }

        /**
         * Generates the `providePlaceholder(KClass<*>): Any` dispatcher — the replacement for the
         * unsafe-cast placeholder mechanism this used to rely on. Every generated `MockXxx` class
         * registers this on its `mocker` (see [mockClassBuilder]'s `init` block), so it's what
         * `References` falls back to when it has no builtin and no user-registered reference for a
         * type — i.e. what `isAny()`/`isEqual()`/etc. need to return from inside an `every { }`.
         *
         * One `when` branch per declaration, in priority order — Fake, then Mock, then Placeholder,
         * each pass skipping a declaration a higher-priority one already claimed, since only the
         * first matching branch of a `when` ever runs and a repeat would be dead code the compiler
         * warns about: fake class/enum first (`fakeFoo()` — the most faithful value available,
         * deduped to one representative per raw class since `KClass` erases generic type arguments —
         * `isAny<GenData<String>>()` and `isAny<GenData<Int>>()` share a branch, and get the most
         * general instantiation available, see [fakes]); mocked interface/abstract class next
         * (`MockFoo(Mocker())` — inert, but a genuine instance of the real type); then placeholder
         * (`placeholderFoo()` — never meant to be genuinely used, and only ever generated for a
         * declaration neither of the above already covers, see [toPlaceholder]). After those: concrete
         * array type (see [placeholderArrayTypes] — `Array<T>` is the one case that *isn't* erased on
         * the JVM), function-type arity (a plain lambda cast to the right shape, matched by the same
         * raw `Function1::class`/etc. `T::class` already erases to — see [placeholderFunctionShapes];
         * one branch per `KClass`, a suspend shape's JVM fallback key never displacing a genuine one),
         * and non-numeric builtin (a literal or factory call matching [builtins] — the numeric ones
         * are already handled by `References`'s own hardcoded primitive map and never reach here):
         *
         * ```
         * internal actual fun providePlaceholder(cls: KClass<*>): Any = when (cls) {
         *     Data::class -> fakeData()
         *     Bar::class -> MockBar(Mocker())
         *     Config::class -> placeholderConfig()
         *     Function1::class -> ({ _ -> error("...") }) as (Any?) -> Any?
         *     String::class -> ""
         *     else -> error("Could not find placeholder for type $cls")
         * }
         * ```
         */
        private fun generatePlaceholderAccessor() {
            val gFile = FileSpec.builder(accessorsPackage, "placeholders")
            val gFun = accessorFunBuilder("providePlaceholder")
                .addAnnotation(AnnotationSpec.builder(Suppress::class).addMember("%S", "UNCHECKED_CAST").build())
                .addParameter("cls", KClass::class.asTypeName().parameterizedBy(STAR))
                .returns(Any::class)

            gFun.beginControlFlow("return when (cls)")

            // Fake first: its members answer with fixed values, the most faithful placeholder
            // available whenever one exists. `cls` is erased, so all of a generic type's
            // instantiations share one branch and one of them has to stand for the rest. Take the most
            // general — every argument its parameter's bound, `GenData<Any>` — the same stand-in the
            // mock branches below use; failing that, the first by generated function name. Both beat
            // `fakes`' hash order, which silently reshuffled the choice whenever an unrelated
            // declaration was added.
            //
            // A fake keyed by a sealed type (e.g. SItf) is generated by constructing a concrete
            // permitted subclass (SItf.C — see resolveSealedTarget). Register both KClasses against
            // the same function: isAny<SItf>() asks for the former, isInstanceOf<SItf.C>() the latter.
            val fakesByDecl = LinkedHashMap<KSClassDeclaration, MemberName>()
            fakes.entries
                .sortedWith(
                    compareByDescending<Map.Entry<KSType, MemberName>> { (type, _) -> type.isBoundedInstantiation() }
                        .thenBy { (_, member) -> member.canonicalName }
                )
                .forEach { (type, member) ->
                    val decl = type.declaration as? KSClassDeclaration ?: return@forEach
                    fakesByDecl.getOrPut(decl) { member }
                    val target = resolveSealedTarget(decl)
                    if (target != decl) fakesByDecl.getOrPut(target) { member }
                }
            fakesByDecl.forEach { (decl, member) -> gFun.addStatement("%T::class -> %M()", decl.toClassName(), member) }

            // Mock second, minus anything a Fake above already claims: an interface (or abstract
            // class) can legitimately have both — a mock is never discovered transitively any more, so
            // this can now only happen when a type is both explicitly requested via @Mock/@UsesMocks
            // and explicitly requested (or transitively required) via @Fake/@UsesFakes.
            mocks.keys
                .filter { itf -> itf !in fakesByDecl }
                .forEach { itf ->
                    val (template, values) = mockConstructorCall(itf)
                    gFun.addStatement("%T::class -> $template", itf.toClassName(), *values.toTypedArray())
                }

            // Placeholder last, minus anything a Fake or a Mock above already claims — which
            // [toPlaceholder] already guarantees never happens (see [seedPlaceholder]/
            // [valueTypeToPlaceholder]), but the filter is repeated here for the same reason the mock
            // pass filters against the fake one: this table is the one place all three kinds meet.
            // [placeholders] is [KSType]-keyed, exactly like [fakes] — same collapse-to-one-branch-
            // per-declaration reasoning as [fakesByDecl] just above, erased `KClass` dispatch being
            // able to use only one branch per declaration regardless of instantiation. A sealed
            // declaration's placeholder is still generated by constructing a concrete permitted
            // subclass ([generatePlaceholderFunction] resolves it the same way [generateFakeFunction]
            // does), so its resolved target needs the same extra branch [fakesByDecl] registers above:
            // isInstanceOf<SItf.C>() asks for it directly, not for the sealed parent isAny<SItf>()
            // asks for.
            val placeholdersByDecl = LinkedHashMap<KSClassDeclaration, MemberName>()
            placeholders.entries
                .sortedWith(
                    compareByDescending<Map.Entry<KSType, MemberName>> { (type, _) -> type.isBoundedInstantiation() }
                        .thenBy { (_, member) -> member.canonicalName }
                )
                .forEach { (type, member) ->
                    val decl = type.declaration as? KSClassDeclaration ?: return@forEach
                    placeholdersByDecl.getOrPut(decl) { member }
                    val target = resolveSealedTarget(decl)
                    if (target != decl) placeholdersByDecl.getOrPut(target) { member }
                }
            placeholdersByDecl.entries
                .filter { (decl, _) -> decl !in fakesByDecl && decl !in mocks }
                .forEach { (decl, member) -> gFun.addStatement("%T::class -> %M()", decl.toClassName(), member) }

            // isInstanceOf<T>()/isEqual<T>() can also target one of a sealed type's OTHER permitted
            // subclasses — not just the one resolveSealedTarget picked for the fake/placeholder
            // function above. An object subclass needs no function call at all: just reference the
            // singleton.
            val sealedObjectSubclasses = LinkedHashSet<KSClassDeclaration>()
            (fakes.keys.mapNotNull { it.declaration as? KSClassDeclaration } + placeholders.keys.mapNotNull { it.declaration as? KSClassDeclaration })
                .filter { Modifier.SEALED in it.modifiers }
                .forEach { sealed -> sealed.getSealedSubclasses().forEach { sub -> if (sub.classKind == ClassKind.OBJECT) sealedObjectSubclasses += sub } }
            sealedObjectSubclasses.forEach { obj -> gFun.addStatement("%T::class -> %T", obj.toClassName(), obj.toClassName()) }

            // `kotlin.Nothing` is excluded alongside the `java.` ones: nothing can ever hold a value
            // of type Nothing, so a `Nothing::class -> throw ...` branch could never be reached —
            // and, unlike every other entry, its "value" isn't one placeholders can hand back.
            //
            // An `external` entry (kotlinx.coroutines, not the Kotlin stdlib) is additionally skipped
            // when the module being processed doesn't have it on its classpath — unlike every stdlib
            // entry, it can't be assumed present, and emitting a `Flow::class -> emptyFlow<Any?>()`
            // branch unconditionally would fail to compile in a module that never mentions Flow.
            builtins.entries
                .filter { (qualifiedName, _) -> !qualifiedName.startsWith("java.") && qualifiedName != "kotlin.Nothing" }
                .filter { (qualifiedName, b) -> !b.external || resolver.getClassDeclarationByName(resolver.getKSNameFromString(qualifiedName)) != null }
                .forEach { (qualifiedName, b) ->
                    // Unlike fakeInitializerOf's use of these same templates (always in a context with
                    // a known target type, e.g. a named constructor argument), this `when` branch's
                    // target type is just `Any` — none of these generic factories (constructors or
                    // top-level `emptyXxx()`/`Xxx()` functions alike) can infer a type argument there,
                    // so it has to be spelled out explicitly, right after the callee name.
                    val placeholderTemplate =
                        if (b.typeArgArity > 0) b.template.replaceFirst("()", "<${List(b.typeArgArity) { "Any?" }.joinToString(", ")}>()")
                        else b.template
                    val pkg = qualifiedName.substringBeforeLast('.')
                    val simple = qualifiedName.substringAfterLast('.')
                    gFun.addStatement("%T::class -> $placeholderTemplate", ClassName(pkg, simple), *b.args.toTypedArray())
                }

            placeholderArrayTypes.forEach { arrType ->
                val componentType = arrType.arguments.first().type!!.resolve().toTypeName()
                val emptyArray = MemberName("kotlin", "emptyArray")
                // A type literal with an explicit type argument (`Array<String>::class`) is JVM-only
                // syntax — Kotlin/Native's parser rejects it outright. An instance-based class
                // literal (the class of an actual, constructed array) works identically everywhere,
                // and — on the JVM specifically — still resolves to the same component-type-specific
                // KClass that `Array<String>::class` would, since JVM arrays reify their component
                // type regardless of how their class is obtained.
                gFun.addStatement("%M<%T>()::class -> %M<%T>()", emptyArray, componentType, emptyArray, componentType)
            }

            // One branch per KClass, since only the first matching one of a `when` ever runs.
            // Every shape claims the declaration KSP resolved it to, and a suspend shape *also* wants
            // `Function<arity+1>::class` (see below) — a key a genuine, non-suspend shape one arity
            // higher may already own. The genuine shape wins: it is the only value that key can be
            // looked up with anywhere except the JVM, and on the JVM erasure makes either lambda
            // satisfy the cast. Registering the fallbacks in a second pass is what enforces that,
            // whatever order the shapes were discovered in.
            val functionShapeBranches = LinkedHashMap<ClassName, Pair<Boolean, Int>>()
            placeholderFunctionShapes.forEach { (decl, isSuspendAndArity) ->
                // Same declaration KSP itself resolved the type to — same as any other interface's
                // `Bar::class` branch.
                functionShapeBranches[decl.toClassName()] = isSuspendAndArity
            }
            placeholderFunctionShapes.values.forEach { isSuspendAndArity ->
                val (isSuspend, arity) = isSuspendAndArity
                if (isSuspend) {
                    // On the JVM specifically, a reified suspend function type's runtime class is its
                    // CPS-transformed backing type (Function(arity+1), continuation appended), not the
                    // frontend-level SuspendFunctionN declaration KSP resolves above — Native's and
                    // Wasm's own reification, unlike the JVM's, does match the frontend declaration.
                    // Since a suspend-shaped lambda genuinely implements both on the JVM, adding this
                    // second branch covers both platforms' actual runtime lookup key.
                    functionShapeBranches.getOrPut(ClassName("kotlin", "Function${arity + 1}")) { isSuspendAndArity }
                }
            }

            functionShapeBranches.forEach { (branchClass, isSuspendAndArity) ->
                val (isSuspend, arity) = isSuspendAndArity
                val shape = buildString {
                    if (isSuspend) append("suspend ")
                    append("(")
                    append(List(arity) { "Any?" }.joinToString(", "))
                    append(") -> Any?")
                }
                // Explicitly typed: JS/Wasm, unlike JVM/Native, don't infer untyped `_` lambda
                // parameters from the surrounding `as Shape` cast.
                val params = if (arity == 0) "" else List(arity) { "_: Any?" }.joinToString(", ") + " -> "
                val message = "The MocKMP processor could not create a placeholder for this function type."
                // A declared-type local val, not a post-hoc `as` cast: a bare lambda literal is
                // always compiled non-suspend, and casting it afterwards is a genuine (failing) cast
                // for a suspend shape, not a no-op — the lambda has to be compiled *as* the target
                // shape from the start, which only a declared-type context (not `as`) provides.
                val value = "run { val f: $shape = { ${params}error(%S) }; f }"
                gFun.addStatement("%T::class -> $value", branchClass, message)
            }

            gFun.addStatement("else -> error(\"Could not find placeholder for type \$cls\")")
            gFun.endControlFlow()

            // providePlaceholder is one shared function covering every branch above, so an opt-in
            // requirement from any one of them — most notably sealedObjectSubclasses, the exact
            // branch responsible for `PolymorphicKind.OPEN::class -> ...` — has to be satisfied on
            // the whole function; a `when` branch can't be annotated on its own.
            optInAnnotation(
                (fakesByDecl.keys + mocks.keys + placeholdersByDecl.keys + sealedObjectSubclasses)
                    .flatMap { it.requiredOptInMarkers() }
                    .distinct()
            )?.let { gFun.addAnnotation(it) }

            gFile.addFunction(gFun.build())
            write(gFile, Dependencies(true))
        }

        // endregion
    }
}
