            // (`fun <T> CompletableDeferred(parent: Job? = null): CompletableDeferred<T>`) — %M, not
            // %T, since it's the function being called, not the interface being constructed (which,
            // like Deferred, has none).
            "kotlinx.coroutines.Deferred" to Builtin("%M()", MemberName("kotlinx.coroutines", "CompletableDeferred"), typeArgArity = 1, external = true),
            "kotlinx.coroutines.CompletableDeferred" to Builtin("%M()", MemberName("kotlinx.coroutines", "CompletableDeferred"), typeArgArity = 1, external = true),
            "kotlinx.coroutines.CoroutineScope" to Builtin("%M(%T)", listOf(MemberName("kotlinx.coroutines", "CoroutineScope"), ClassName("kotlin.coroutines", "EmptyCoroutineContext")), external = true),
            "kotlinx.coroutines.sync.Mutex" to Builtin("%M()", MemberName("kotlinx.coroutines.sync", "Mutex"), external = true),
            "kotlinx.coroutines.sync.Semaphore" to Builtin("%M(1)", MemberName("kotlinx.coroutines.sync", "Semaphore"), external = true),
        )
    }

    private val KSType.isAnyFunctionType get() = isFunctionType || isSuspendFunctionType

    /**
     * Follows type alias declarations (e.g. `typealias BarCB = (String) -> Int`, or the built-in
     * `kotlin.Exception` resolving to `java.lang.Exception` on the JVM target) down to the real
     * type they expand to. Every site that treats a [KSType] as the identity of a fake
     * (registration, lookup, and generated-name derivation alike) must resolve through this first,
     * or an aliased type and its underlying type would be treated as two different fakes.
     */
    private fun KSType.unwrapAliases(): KSType {
        var t = this
        while (t.declaration is KSTypeAlias) t = (t.declaration as KSTypeAlias).type.resolve()
        return t
    }

    /** Follows `typealias` chains to the underlying declaration. */
    private fun KSType.aliasedDeclaration(): KSDeclaration = unwrapAliases().declaration

    /** True when [this] type is `kotlin.Unit`, through any `typealias`. */
    private fun KSType.isUnit(): Boolean = aliasedDeclaration().qualifiedName?.asString() == "kotlin.Unit"

    /** True when [this] type is `kotlin.Nothing`, through any `typealias`. */
    private fun KSType.isNothing(): Boolean = aliasedDeclaration().qualifiedName?.asString() == "kotlin.Nothing"

    private val visibilityModifier = if (public) KModifier.PUBLIC else KModifier.INTERNAL

    /**
     * Whether the four accessors have been written, across *all* rounds — unlike [Round], this
     * processor outlives them.
     *
     * Generating files causes KSP to run another round, in which no annotated symbol is found, so
     * emitting the accessors on a "did we collect anything" condition doubled as the guard against
     * writing them twice. They are now emitted whether or not anything was collected, and this is
     * what keeps the second round from rewriting them.
     */
    private var accessorsGenerated = false

    /**
     * Thrown to abort processing of the current round with a location-tagged message. Deliberately
     * *not* named `Error`: it shadowed `kotlin.Error` in [process], which made the `catch` below read
     * like a catch-all when it was the narrowest possible catch.
     */
    private class ProcessingError(message: String, val node: KSNode) : Exception(message)

    override fun process(resolver: Resolver): List<KSAnnotated> =
        try {
            Round(resolver).run()
        } catch (e: ProcessingError) {
            logger.error("MocKMP: ${e.message}", e.node)
            if (throwErrors) throw e
            emptyList()
        } catch (e: Exception) {
            // Anything reaching here is a MocKMP bug, not bad user input — but it used to surface as
            // a raw KSP crash, with nothing saying which processor produced it or what to do about
            // it. The stack trace is included because catching without it would lose the one KSP
            // prints today, making a bug report harder to file rather than easier.
            logger.error(
                "MocKMP: internal error: ${e::class.simpleName}: ${e.message}\n" +
                        "This is a bug in MocKMP. Please open an issue at https://github.com/kosi-libs/MocKMP/issues/new, " +
                        "including the stack trace below and, if you can, the declaration being processed.\n" +
                        e.stackTraceToString()
            )
            if (throwErrors) throw e
            emptyList()
        }

    // region Error reporting

    /** Renders [this] node as a human-readable path, for messages when no [FileLocation] is available. */
    private fun KSNode.asString(): String = when (this) {
        is KSValueParameter -> {
            val nameStr = name?.asString() ?: "?"
            if (parent != null) "${parent!!.asString()}($nameStr)"
            else nameStr
        }
        is KSClassDeclaration -> this.qualifiedName?.asString() ?: this.simpleName.asString()
        else -> (parent?.let { it.asString() + "." } ?: "") + toString()
    }

    /** Fails the current round with [message], pointing [logger] at [node]'s source location when known. */
    private fun error(node: KSNode, message: String): Nothing {
        val prefix = when (val loc = node.location) {
            is FileLocation -> "$node (${loc.filePath}:${loc.lineNumber})"
            is NonExistLocation -> node.asString()
        }
        throw ProcessingError("$prefix: $message", node)
    }

    /** `qualifiedName`, falling back to `simpleName` for local/anonymous declarations. */
    private fun KSDeclaration.displayName(): String = qualifiedName?.asString() ?: simpleName.asString()

    /** Plural of a class kind, so reason clauses read naturally ("interfaces cannot be instantiated"). */
    private fun ClassKind.plural(): String = when (this) {
        ClassKind.CLASS -> "classes"
        ClassKind.ENUM_CLASS -> "enum classes"
        ClassKind.ENUM_ENTRY -> "enum entries"
        ClassKind.INTERFACE -> "interfaces"
        ClassKind.OBJECT -> "objects"
        ClassKind.ANNOTATION_CLASS -> "annotation classes"
    }

    /**
     * The single wording for "this type cannot be faked", shared by the compile-time error
     * ([cannotFake]) and the runtime stub ([Round.reportUnfakeable]). [reason] is a clause
     * completing "... because <reason>.".
     *
     * [path] is why the type was needed at all (see [ToProcess.path]) — almost never something the
     * user wrote themselves, since a fake is usually reached transitively, so the failing type alone
     * would leave them with no way back to their own declaration. Omitted for a type requested
     * directly, where there is nothing to explain.
     */
    private fun unfakeableMessage(displayName: String, reason: String, path: List<String>): String =
        buildString {
            append("Cannot generate a fake for $displayName because $reason.")
            if (path.isNotEmpty()) append("\nRequired by: ${path.joinToString(" -> ")}")
            append("\nPlease register a top-level @FakeProvider function that provides a value of this type.")
        }

    /** Aborts the round: [displayName] cannot be faked because [reason]. */
    private fun cannotFake(node: KSNode, displayName: String, reason: String, path: List<String>): Nothing =
        error(node, unfakeableMessage(displayName, reason, path))

    // endregion

    // region Requirement paths

    /**
     * [this] type as one step of a requirement path names it: simple name, type arguments and
     * nullability, but no package. A path is read for orientation — `Network(TCPLayer, Int)` rather
     * than `foo.Network(foo.TCPLayer, kotlin.Int)` — and every step but the first is introduced by
     * the step before it, which already says which type it landed on.
     */
    private fun KSType.pathName(): String {
        val resolved = unwrapAliases()
        val arguments =
            if (resolved.arguments.isEmpty()) ""
            else resolved.arguments.joinToString(", ", "<", ">") {
                if (it.variance == Variance.STAR) "*" else it.type?.resolve()?.pathName() ?: "*"
            }
        return resolved.declaration.simpleName.asString() + arguments + (if (isMarkedNullable) "?" else "")
    }

    /** `(TCPLayer, vararg Int)`: the parameter type list shared by the function and constructor steps. */
    private fun parametersPathName(parameters: List<KSValueParameter>, types: List<KSType?>): String =
        parameters.mapIndexed { index, vParam ->
            val type = types.getOrNull(index)?.pathName() ?: "?"
            if (vParam.isVararg) "vararg $type" else type
        }.joinToString(", ", "(", ")")

    /** `Database.con: Connection` — [owner]'s property [vProp], of [type], required a fake of it. */
    private fun propertyPathStep(owner: String, vProp: KSPropertyDeclaration, type: KSType): String =
        "$owner.${vProp.simpleName.asString()}: ${type.pathName()}"

    /** `Connection.connect(String): Network` — [owner]'s function [vFun] required a fake of its return type. */
    private fun functionPathStep(owner: String, vFun: KSFunctionDeclaration, parameterTypes: List<KSType?>, returnType: KSType?): String =
        "$owner.${vFun.simpleName.asString()}${parametersPathName(vFun.parameters, parameterTypes)}: ${returnType?.pathName() ?: "?"}"

    /** `Network(TCPLayer, Int)` — constructing [owner] required a fake of each of these parameter types. */
    private fun constructorPathStep(owner: String, vCstr: KSFunctionDeclaration): String =
        owner + parametersPathName(vCstr.parameters, vCstr.parameters.map { it.type.resolve() })

    // endregion

    /** The files and annotation sites that referenced a to-be-generated mock or fake, accumulated across annotations. */
    private class ToProcess {
        val files = LinkedHashSet<KSFile>()
        val references = LinkedHashSet<KSNode>()

        /**
         * True when this entry was discovered implicitly — as a type reachable from a mocked
         * interface's signatures (see [Round.seedImplicitPlaceholders]), not requested directly via
         * `@Mock`/`@Fake`/`@UsesMocks`/`@UsesFakes`. Implicit entries that turn out to be
         * unconstructible get a generated function that throws at runtime instead of aborting the
         * KSP round — nobody asked for that type directly, so failing the whole build over it would
         * be disproportionate. Explicit entries keep failing fast at compile time.
         */
        var implicit: Boolean = false

        /**
         * The declarations that led to this entry, one rendered step each, ending with the one that
         * required this very type — empty for a type requested directly by an annotation.
         *
         * Recorded during discovery rather than reconstructed at failure time: by the time a type
         * turns out to be unfakeable, whether in [Round.addFake] or as late as generation, the walk
         * that reached it is long over. Since entries are deduplicated on first registration and the
         * expansion worklist is breadth-first, this is the shortest chain that reaches the type.
         */
        var path: List<String> = emptyList()
    }

    /** One abstract member of an implemented type needing a fake: what to fake, what to blame, and the path step it adds. */
    private class MemberToFake(val type: KSType, val node: KSNode, val step: String)

    // region Naming

    /** The `Outer_Inner_` prefix identifying [this] declaration's chain of enclosing declarations, if any. */
    private fun KSDeclaration.parentPrefix(): String = buildString {
        var pDecl = parentDeclaration
        while (pDecl != null) {
            append(pDecl.simpleName.asString())
            append("_")
            pDecl = pDecl.parentDeclaration
        }
    }

    /** The `foo_bar_` prefix identifying [this] declaration's package, empty for the root package. */
    private fun KSDeclaration.packagePrefix(): String =
        packageName.asString().replace('.', '_').withNonEmptySuffix("_")

    /**
     * A name-safe identifier for the `fakeXxx()` function generated for [this] type: unique per
     * package (`fakedata_Data` vs. `fakefoo_Data`, since both live in the same generated
     * `fakes.kt`), distinct type argument list (`fakeGenDataXkotlin_IntX`, `fakeGenDataXkotlin_StringX`,
     * ...), nesting (`fakeFakeTests_FakeAny` for a nested class `FakeAny` inside `FakeTests`) and
     * nullability.
     */
    private fun KSType.toFunName(): String {
        val decl = aliasedDeclaration()
        return decl.packagePrefix() + (if (isMarkedNullable) "Nul" else "") + baseName()
    }

    /**
     * The package-independent part of [toFunName]: nesting, simple name, and type argument list.
     * Split out because the class name generated for a faked interface ([toFakeClassName]) needs
     * exactly this and *not* the package prefix — it lives in the faked type's own package, where
     * the prefix would only be noise, while a `fakeXxx()` function needs it (see [toFunName]).
     */
    private fun KSType.baseName(): String {
        val resolved = unwrapAliases()
        val decl = resolved.declaration
        return decl.parentPrefix() +
                if (resolved.arguments.isEmpty()) decl.simpleName.asString()
                else "${decl.simpleName.asString()}X${
                    resolved.arguments.joinToString("_") {
                        if (it.variance == Variance.STAR) "STAR"
                        else it.type!!.resolve().toFunName()
                    }
                }X"
    }

    /**
     * The `FakeXxx` class name generated for [this] faked interface or abstract class. Unlike
     * [toMockName], it carries the type arguments ([baseName]): a `MockXxx` is generic and defers
     * every member to its `Mocker`, whereas a fake has to *hold* values, so one class is generated
     * per faked instantiation (`FakeFooXkotlin_StringX : Foo<String>`).
     */
    private fun KSType.toFakeClassName(): String = "Fake" + baseName()

    /** The `MockXxx` class name generated for [this] mocked interface. */
    private fun KSDeclaration.toMockName(): String = "Mock" + parentPrefix() + simpleName.asString()

    /**
     * The package a generated `fakeXxx()`/`MockXxx` declaration for [this] declaration is emitted
     * into: its own package, except for protected packages (the Kotlin stdlib and the JDK, which
     * this module cannot write into — see [isProtectedPackage]), redirected under a local `fake.`
     * prefix.
     */
    private fun KSDeclaration.fakePackageName(): String =
        if (packageName.isProtectedPackage()) "fake." + packageName.asString() else packageName.asString()

    // endregion

    /**
     * Mutable state and generation logic of a single KSP processing round. A fresh instance is
     * created per [process] call, so [MocKMPProcessor] itself carries no state across rounds.
     */
    private inner class Round(private val resolver: Resolver) {

        // Every collection below is insertion-ordered on purpose. Several of them are iterated to
        // emit `when` branches or whole files, so a `HashMap` would order generated code by hash:
        // stable for a given input, but reshuffling the entire file whenever an unrelated
        // declaration is added. Insertion order follows the order KSP hands the symbols over —
        // i.e. source order — so adding a declaration inserts a line instead of rewriting the file.

        /** Interfaces referenced by `@Mock`/`@UsesMocks`, with the files/nodes that referenced them. */
        private val toMock = LinkedHashMap<KSClassDeclaration, ToProcess>()

        /** Generated `MockXxx` class name, per mocked interface — consumed by [generateMockAccessor]. */
        private val mocks = LinkedHashMap<KSClassDeclaration, ClassName>()

        /** Types referenced by `@Fake`/`@UsesFakes`, or required transitively (see [expandTransitiveFakes]). */
        private val toFake = LinkedHashMap<KSType, ToProcess>()

        /** Generated `fakeXxx()` function name, per faked type — consumed by [generateFakeAccessor]. */
        private val fakes = LinkedHashMap<KSType, MemberName>()

        /** User-supplied `@FakeProvider` functions, keyed by the type they provide a fake for. */
        private val providedFakes = LinkedHashMap<KSType, KSFunctionDeclaration>()

        /**
         * True when a faked property of [this] type should be wrapped `by LazyFake { ... }` instead of
         * getting a plain initializer — every case where [fakeValueOf] resolves to a nested `fakeXxx()`
         * or `@FakeProvider` call rather than a literal. Deferring that call is what lets a
         * self-referential type (`interface Node { val parent: Node }`) be faked at all: an eager
         * `override val parent: Node = fakeNode()` would recurse building its own `parent`, forever.
         *
         * A member of [Round], unlike the rest of the small `KSType` predicates above it, because it
         * has to consult [providedFakes]: a `@FakeProvider`-backed value is a function call too, and
         * needs the same deferral as a nested `fakeXxx()` call.
         *
         * `null`, a lambda literal, and a plain (non-`StateFlow`) builtin (see [builtins]) are
         * excluded: their value is already either not built at all, or built without recursing into
         * another `fakeXxx()`/provider call. `StateFlow<T>`/`MutableStateFlow<T>` is a builtin that
         * *can* need one — `MutableStateFlow(fakeFoo())` — so it defers to whether its type argument does.
         */
        private fun KSType.needsLazyFake(): Boolean {
            if (nullability != Nullability.NOT_NULL) return false
            if (isAnyFunctionType) return false
            val resolvedType = unwrapAliases()
            if (resolvedType in providedFakes) return true
            val qualifiedName = resolvedType.declaration.qualifiedName?.asString()
            if (qualifiedName == "kotlinx.coroutines.flow.StateFlow" || qualifiedName == "kotlinx.coroutines.flow.MutableStateFlow") {
                return resolvedType.arguments.first().type!!.resolve().needsLazyFake()
            }
            return qualifiedName !in builtins
        }

        /** Properties annotated `@Mock`/`@Fake`, grouped by enclosing class — consumed by [generateInjector]. */
        private val toInject = LinkedHashMap<KSClassDeclaration, ArrayList<Pair<String, KSPropertyDeclaration>>>()

        /**
         * Concrete `Array<T>` types (a known component type) needing a placeholder — kept separate
         * from [toFake]/[toMock] because, unlike ordinary generics, `Array<T>::class` is *not*
         * erased on the JVM: each component type is a genuinely distinct runtime class, so
         * `Array<String>::class` and `Array<Int>::class` can't share one `when` branch the way
         * `List<String>::class == List<Int>::class` can. Consumed by [generatePlaceholderAccessor].
         */
        private val placeholderArrayTypes = LinkedHashSet<KSType>()

        /**
         * Function-typed shapes found while seeding implicit placeholders, keyed by the exact
         * declaration KSP resolves the type to (`kotlin.Function1`, `kotlin.coroutines.SuspendFunction1`,
         * etc. — deliberately *not* hand-built from an arity count: the JVM backend's CPS transform
         * means a suspend type's *reified* runtime class doesn't necessarily follow the naming
         * scheme its own frontend declaration suggests, so reusing KSP's own resolution is the only
         * reliable way to get a matching `T::class`). Mapped to (isSuspend, parameterCount), needed
         * to build the placeholder lambda's shape. Kept separate from [toMock] — a generated class
         * can't `: Function1<P1, R>` on Kotlin/JS ("Implementing a function interface is prohibited
         * in JavaScript"), so a plain lambda is used instead — consumed by [generatePlaceholderAccessor].
         */
        private val placeholderFunctionShapes = LinkedHashMap<KSClassDeclaration, Pair<Boolean, Int>>()

        /** Runs the full pipeline for this round: collect, expand, then generate every kind of file. */
        fun run(): List<KSAnnotated> {
            collectAnnotatedSymbols()
            collectFakeProviders()
            seedImplicitPlaceholders()
            expandTransitiveFakes()

            toMock.forEach { (vItf, process) -> generateMockClass(vItf, process) }
            toFake.forEach { (vType, process) -> generateFakeFunction(vType, process) }
            toInject.forEach { (vCls, _) -> generateInjector(vCls) }

            // Unconditionally, even with nothing to dispatch: the Gradle plugin always writes the
            // matching declarations into the source set, as `expect`s for a multiplatform project and
            // as inline `mock()`/`fake()` for a single-target one, so a project that applies the
            // plugin before annotating anything would otherwise not compile. Each generator emits an
            // `error("No … declared")` body for the empty case.
            if (!accessorsGenerated) {
                accessorsGenerated = true
                generateMockAccessor()
                generateFakeAccessor()
                generateInjectorAccessor()
                generatePlaceholderAccessor()
            }

            return emptyList()
        }

        // region Phase 1: collect annotated symbols

        /**
         * Registers [type] as needing a `MockXxx` class, or fails if it isn't an interface or an
         * abstract class. [implicit] marks entries discovered by [seedImplicitPlaceholders] rather
         * than requested directly, and [path] records what led here (see [ToProcess.path]) — a mock
         * never reports it, but the fakes discovered from its members inherit it.
         */
        private fun addMock(type: KSType, files: Iterable<KSFile>, node: KSNode, implicit: Boolean = false, path: List<String> = emptyList()) {
            // Suspend function types included: KSP presents `kotlin.coroutines.SuspendFunctionN` as an
            // interface, so testing only isFunctionType let a `suspend (A) -> R` property through to
            // the mocked-interface path and generated a class implementing that compiler-synthesized
            // supertype. [addMockInjection] builds these with mockFunctionN/mockSuspendFunctionN.
            if (type.isAnyFunctionType) return
            val decl = type.declaration
            val isMockable = decl is KSClassDeclaration &&
                    (decl.classKind == ClassKind.INTERFACE || (decl.classKind == ClassKind.CLASS && Modifier.ABSTRACT in decl.modifiers))
            if (!isMockable) error(node, "Cannot generate mock for non interface $decl")
            toMock.getOrPut(decl) { ToProcess().apply { this.implicit = implicit; this.path = path } }.let {
                it.files.addAll(files)
                it.references.add(node)
            }
        }

        /**
         * Registers [type] as needing a `fakeXxx()` function, or fails if it isn't a fakeable
         * type — resolved the same way [valueTypeToFake] resolves a nested occurrence, so the two
         * agree on what "the type to fake" actually is here: nullable, builtin, and function types
         * are silently skipped rather than validated, exactly as they would be if [type] were
         * reached as a constructor parameter or an implemented member instead of directly (a
         * nullable value is simply `null`; a builtin's value is a literal, see [fakeInitializerOf];
         * a function type's value is an inline lambda, never a generated implementation of
         * `Function1` & co. — which Kotlin/JS forbids a class from declaring as a supertype — so
         * only its return type, if any, might still need registering). [type] is also resolved
         * through any `typealias` chain (e.g. `kotlin.Exception` on the JVM target), so the
         * registration key, and every check below, target the real underlying type. Sealed
         * classes/interfaces are allowed through — [generateFakeFunction] resolves them to a
         * constructible permitted subclass at generation time. [implicit] marks entries discovered
         * by [seedImplicitPlaceholders] rather than requested directly, and [path] records what led
         * here — reported by every rejection below, and by [reportUnfakeable] when the type only
         * turns out to be unfakeable at generation time.
         *
         * Interfaces and abstract classes are fakeable too: rather than being instantiated, they get
         * a generated `FakeXxx` implementation (see [addFakeImplementation]). Objects and annotation
         * classes are fakeable as well — a bare reference to the singleton, and a constructor call,
         * respectively (see [generateFakeFunction]). What is left to reject here is a type parameter
         * or other non-class declaration, neither of which is a builtin either.
         */
        private fun addFake(type: KSType, files: Iterable<KSFile>, node: KSNode, implicit: Boolean = false, path: List<String> = emptyList()) {
            // Syntactic nullability (`T?`), not KSP's semantic Nullability enum: unlike every other
            // caller of this "skip if nullable" idiom (valueTypeToFake, fakeValueOf), [type] here can
            // be a bare, unsubstituted type parameter straight off a property declaration — and KSP
            // reports Nullability.NULLABLE for one of those whenever its bound is (or defaults to)
            // nullable, same as it does for a genuinely nullable type, even though nothing marks it
            // with `?`. Falling through on that would silently swallow `@Fake lateinit var x: T`
            // (inside the very class `T` belongs to) as "nothing to do", instead of correctly still
            // reaching the type-parameter rejection below — there is no concrete type to construct a
            // value of, so not even `null` is a valid instance of a type that isn't marked nullable.
            if (type.isMarkedNullable) return
            var resolvedType = type.unwrapAliases()
            if (resolvedType.isAnyFunctionType) {
                // Two shapes can't be unwrapped to a fakeable return type: a raw, unparameterized
                // reference — only reachable from a KClass literal (e.g.
                // `@UsesFakes(Function1::class)`), never from a genuine declared type — has none at
                // all; and a function *returning* a function, whose return type is itself a function
                // type. Both are rejected the same way a plain function type always was: registering
                // the inner function type would only "succeed" by generating exactly the shape this
                // check exists to prevent — a class declaring Function1 & co. as a supertype, which
                // Kotlin/JS forbids — since fakeValueOf's inline lambda generation only inlines one
                // level itself (it calls fakeInitializerOf directly on the return type, which has no
                // function-type handling of its own).
                val returnType = resolvedType.arguments.lastOrNull()?.type?.resolve()
                if (returnType == null || returnType.isAnyFunctionType) {
                    error(node, "Cannot generate a fake for the function type ${resolvedType.toTypeName()}. Please use @Mock instead, which mocks a function type as a callable mock.")
                }
                resolvedType = returnType.unwrapAliases()
            }
            val decl = resolvedType.declaration
            val qualifiedName = decl.qualifiedName?.asString()

            // Unlike every other builtin, StateFlow/MutableStateFlow's value embeds a faked instance
            // of its type argument (see fakeInitializerOf) — so, unlike returning outright below,
            // that argument still has to be registered here, exactly as a constructor parameter type
            // would be by expandTransitiveFakes.
            if (qualifiedName == "kotlinx.coroutines.flow.StateFlow" || qualifiedName == "kotlinx.coroutines.flow.MutableStateFlow") {
                resolvedType.arguments.firstOrNull()?.type?.resolve()
                    ?.let { addFake(it, files, node, implicit, path) }
                return
            }

            if (qualifiedName in builtins) return

            if (decl !is KSClassDeclaration) {
                val reason = if (decl is KSTypeParameter) "it is a type parameter, which has no concrete type to construct" else "it is not a class"
                cannotFake(node, decl.displayName(), reason, path)
            }
            val isSealed = Modifier.SEALED in decl.modifiers
            if (!isSealed && decl.classKind !in arrayOf(ClassKind.CLASS, ClassKind.ENUM_CLASS, ClassKind.INTERFACE, ClassKind.OBJECT, ClassKind.ANNOTATION_CLASS)) {
                cannotFake(node, decl.displayName(), "${decl.classKind.plural()} cannot be instantiated", path)
            }
            toFake.getOrPut(resolvedType) { ToProcess().apply { this.implicit = implicit; this.path = path } }.let {
                it.files.addAll(files)
                it.references.add(node)
            }
        }

        /** Finds every property annotated [annotationName] (or its setter), registers its class for injection, and [add]s its type. */
        private fun lookUpFields(annotationName: String, add: (KSType, Iterable<KSFile>, KSNode) -> Unit) {
            val symbols = resolver.getSymbolsWithAnnotation(annotationName)
            symbols.forEach { symbol ->
                val prop = when (symbol) {
                    is KSPropertySetter -> symbol.receiver
                    is KSPropertyDeclaration -> {
                        if (!symbol.isMutable) error(symbol, "$symbol is immutable but is annotated with @${annotationName.split(".").last()}")
                        symbol
                    }
                    else -> error(symbol, "$symbol is not a property nor a property setter but is annotated with @${annotationName.split(".").last()} (is ${symbol::class.simpleName})")
                }
                val cls = prop.parentDeclaration as? KSClassDeclaration ?: error(symbol, "Cannot generate injector for $prop as it is not inside a class")
                toInject.getOrPut(cls) { ArrayList() }.add(annotationName to prop)
                add(prop.type.resolve(), listOf(cls.containingFile!!), symbol)
            }
        }

        /** Finds every declaration annotated `@UsesMocks(...)`/`@UsesFakes(...)` and [add]s each type listed in [annotationName]'s array argument. */
        private fun lookUpUses(annotationName: String, add: (KSType, Iterable<KSFile>, KSNode) -> Unit) {
            val uses = resolver.getSymbolsWithAnnotation(annotationName)
            uses.forEach { use ->
                val anno = use.annotations.first { it.annotationType.resolve().declaration.qualifiedName!!.asString() == annotationName }
                (anno.arguments.first().value as List<*>).forEach {
                    add((it as KSType), listOf(use.containingFile!!), use)
                }
            }
        }

        /** Populates [toMock], [toFake] and [toInject] from `@Mock`, `@Fake`, `@UsesMocks` and `@UsesFakes`. */
        private fun collectAnnotatedSymbols() {
            lookUpFields(ANNOTATION_MOCK, ::addMock)
            lookUpFields(ANNOTATION_FAKE, ::addFake)
            lookUpUses(ANNOTATION_USES_MOCKS, ::addMock)
            lookUpUses(ANNOTATION_USES_FAKES, ::addFake)
        }

        /**
         * Populates [providedFakes] from `@FakeProvider` top-level functions, and removes their
         * return type from [toFake] — a user-supplied provider makes generation unnecessary. The
         * return type is resolved through any `typealias` chain first, matching every other site
         * that uses a [KSType] as a fake's identity (see [unwrapAliases]) — so a provider
         * declared to return `Exception` registers under the same key `addFake`/`fakeInitializerOf`
         * look up for a `kotlin.Exception`-typed parameter.
         */
        private fun collectFakeProviders() {
            resolver.getSymbolsWithAnnotation(ANNOTATION_FAKE_PROVIDER).forEach {
                if (it !is KSFunctionDeclaration || it.parent !is KSFile) error(it, "Only top-level functions can be annotated with @FakeProvider")
                val type = it.returnType!!.resolve().unwrapAliases()
                val typeDeclaration = type.declaration
                if (typeDeclaration !is KSClassDeclaration) error(it, "@FakeProvider functions must return class types.")
                if (type in providedFakes) error(it, "Only one @FakeProvider function must exist for this type (other is ${providedFakes[type]!!.asString()}).")
                toFake.remove(type)
                providedFakes[type] = it
            }
        }

