/**
 * KSP [SymbolProcessor] that powers MocKMP code generation.
 *
 * Each processing round ([process]) scans the module for MocKMP annotations and emits three kinds
 * of files, in this order:
 *
 * - **Mocks**: for every interface referenced by `@Mock` or `@UsesMocks(...)`, a `MockXxx` class
 *   implementing it, delegating every member to an injected [org.kodein.mock.Mocker]
 *   (see [Round.generateMockClass]).
 * - **Fakes**: for every type referenced by `@Fake`, `@UsesFakes(...)`, or transitively required
 *   as a non-nullable, non-defaulted constructor parameter of another fake, a top-level
 *   `fakeXxx(): Xxx` function that builds a placeholder instance (see [Round.generateFakeFunction]).
 * - **Injectors**: for every class with `@Mock`/`@Fake` annotated properties, a
 *   `Mocker.injectMocks(receiver: Xxx)` function that sets them all (see [Round.generateInjector]).
 *
 * Once at least one mock or fake exists, three small dispatch functions are additionally emitted
 * into [accessorsPackage] — `Mocker.mock(KClass<T>): T`, `fake(KType): T` and
 * `Mocker.injectMocks(Any)` — matching the `expect` declarations generated by the MocKMP Gradle
 * plugin (see `mockmp-gradle-plugin/src/main/resources/mockmp.multi.kt`).
 *
 * The whole pipeline for a single round is implemented by [Round], instantiated fresh on every
 * [process] call so this processor itself carries no state between rounds.
 */
class MocKMPProcessor(
    private val codeGenerator: CodeGenerator,
    private val logger: KSPLogger,
    private val throwErrors: Boolean,
    public: Boolean,
    private val accessorsPackage: String,
    private val multiplatform: Boolean,
) : SymbolProcessor {

    private companion object {
        val mockerTypeName = ClassName("org.kodein.mock", "Mocker")
        val lazyFakeTypeName = ClassName("org.kodein.mock", "LazyFake")

        // Fully-qualified names of the annotations MocKMP looks for.
        const val ANNOTATION_MOCK = "org.kodein.mock.Mock"
        const val ANNOTATION_FAKE = "org.kodein.mock.Fake"
