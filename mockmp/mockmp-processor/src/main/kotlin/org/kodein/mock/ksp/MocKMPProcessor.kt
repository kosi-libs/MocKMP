        // region Phase 1.5: placeholder seeding

        /**
         * A representative [KSType] for [this] declaration, substituting each type parameter with
         * its first bound (e.g. `T : Any` becomes `Any`) — the same "good enough" stand-in
         * [generateMockAccessor] already uses when the concrete type argument is unknown.
         */
        private fun KSClassDeclaration.asBoundedType(): KSType =
            asType(typeParameters.map { resolver.getTypeArgument(it.bounds.first(), Variance.INVARIANT) })

        /** The stand-in type for [this] type parameter when no argument is known: its first bound, or `Any?`. */
        private fun KSTypeParameter.boundType(): KSType =
            bounds.firstOrNull()?.resolve() ?: resolver.builtIns.anyType.makeNullable()

        /**
         * [this] type with every type argument that isn't a fully concrete type — a star
         * projection, a missing argument, or an argument that (at any depth) mentions a type
         * parameter — replaced by the matching parameter's own bound, as [asBoundedType] does.
         *
         * What a generated fake/placeholder implementation is written against, and what a
         * placeholder or a Mock is keyed and instantiated at ([seedPlaceholder],
         * [generatePlaceholderFunction], [mockConstructorCall]): a class cannot declare a
         * star-projected supertype (`class FakeItf : Itf<*>` does not compile), a member's type
         * cannot be substituted through one either, and neither can carry a reference to a type
         * parameter that belongs to some other, unrelated scope — e.g. a mocked interface's own
         * generic member, `fun <T> encode(serializer: KSerializer<T>)`, whose `T` means nothing
         * outside that one function. There is no concrete type to substitute such a mention with, so
         * the class's own declared parameter bound stands in instead, exactly as it already does for
         * a star projection — deliberately *not* resolved further through the mentioned parameter's
         * own bound, which would recurse forever for an F-bounded one (`fun <T: Comparable<T>> ...`).
         * `Itf<Any>` is the closest implementable instantiation, and remains a subtype of the
         * `Itf<*>` its `fakeXxx()` function returns.
         */
        private fun KSType.withBoundArguments(): KSType {
            val decl = declaration as? KSClassDeclaration ?: return this
            if (decl.typeParameters.isEmpty()) return this
            if (arguments.size != decl.typeParameters.size) return decl.asBoundedType()
            fun KSTypeArgument.isConcrete() = variance != Variance.STAR && type != null && type?.resolve()?.mentionsTypeParameter() != true
            if (arguments.all { it.isConcrete() }) return this
            val boundArguments = decl.typeParameters.zip(arguments).map { (vParam, argument) ->
                if (argument.isConcrete()) argument
                else resolver.getTypeArgument(resolver.createKSTypeReferenceFromKSType(vParam.boundType()), Variance.INVARIANT)
            }
            return replace(boundArguments)
        }

        /** True when [this] type is, or contains at any depth, a reference to a type parameter. */
        private fun KSType.mentionsTypeParameter(): Boolean =
            declaration is KSTypeParameter || arguments.any { it.type?.resolve()?.mentionsTypeParameter() == true }

        /**
         * [this] type, rendered for a generated *member signature*.
         *
         * Identical to [toTypeName] except for function types, which are written back as lambdas:
         * KSP resolves them to their underlying declaration, which `toTypeName` then renders
         * literally — `Function1<String, Int>` for `(String) -> Int`, which merely reads oddly, but
         * `SuspendFunction1<String, Int>` for `suspend (String) -> Int`, which is a
         * compiler-internal declaration that cannot be written in Kotlin source at all.
         *
         * Member types have to go through this because they come from
         * [KSPropertyDeclaration.asMemberOf], which yields a [KSType] with the declared syntax lost;
         * mocked members keep theirs by rendering their [KSTypeReference] instead.
         */
        private fun KSType.toMemberTypeName(typeParamResolver: TypeParameterResolver = TypeParameterResolver.EMPTY): TypeName {
            if (!isAnyFunctionType) return toTypeName(typeParamResolver)
            val argumentTypes = arguments.map { it.type!!.resolve().toMemberTypeName(typeParamResolver) }
            // `A.() -> B` and `(A) -> B` share one underlying declaration, told apart only by this
            // annotation; an override has to repeat the form its supertype declares.
            val isExtension = annotations.any { it.shortName.asString() == "ExtensionFunctionType" }
            val parameterTypes = argumentTypes.dropLast(1)
            return LambdaTypeName.get(
                receiver = if (isExtension) parameterTypes.first() else null,
                parameters = (if (isExtension) parameterTypes.drop(1) else parameterTypes).map { ParameterSpec.unnamed(it) },
                returnType = argumentTypes.last(),
            ).copy(suspending = isSuspendFunctionType, nullable = isMarkedNullable)
        }

        /**
         * True when every type argument of [this] is its own parameter's bound (`GenData<Any>` for
         * `GenData<out T : Any>`) — the most general instantiation, and what [asBoundedType] builds.
         * Trivially true for a non-generic type.
         */
        private fun KSType.isBoundedInstantiation(): Boolean {
            val decl = declaration as? KSClassDeclaration ?: return false
            if (arguments.size != decl.typeParameters.size) return false
            return decl.typeParameters.zip(arguments).all { (vParam, argument) -> argument.type?.resolve() == vParam.boundType() }
        }

        /**
         * If [decl] is sealed (class or interface), returns its first permitted subclass, resolved
         * recursively through nested sealed hierarchies. Returns [decl] unchanged when it isn't
         * sealed, or when a sealed hierarchy has no permitted subclasses (construction then fails
         * naturally later, with a reasonable "no public constructor" message).
         *
         * [resolveSealedTargetType] is the type-level counterpart, and must keep picking the same
         * subclass as this one.
         */
        private fun resolveSealedTarget(decl: KSClassDeclaration): KSClassDeclaration {
            if (Modifier.SEALED !in decl.modifiers) return decl
            val first = decl.getSealedSubclasses().firstOrNull() ?: return decl
            return resolveSealedTarget(first)
        }

        /**
         * Binds the type parameters [declared] is written in terms of to the matching arguments of
         * [actual], recursively — unifying `Swapped<Y, X>` against `Swapped<String, Int>` binds
         * `Y` to `String` and `X` to `Int`.
         */
        private fun bindTypeParameters(declared: KSType, actual: KSType, into: MutableMap<KSTypeParameter, KSType>) {
            val decl = declared.declaration
            if (decl is KSTypeParameter) {
                into[decl] = actual
                return
            }
            declared.arguments.forEachIndexed { index, argument ->
                val declaredArgument = argument.type?.resolve() ?: return@forEachIndexed
                val actualArgument = actual.arguments.getOrNull(index)?.type?.resolve() ?: return@forEachIndexed
                bindTypeParameters(declaredArgument, actualArgument, into)
            }
        }

        /**
         * [resolveSealedTarget] at the type level: the permitted subclass that will actually be
         * constructed for [vType], expressed with *its own* type arguments.
         *
         * A subclass does not have to declare the same type parameters, in the same order, as the
         * sealed parent it extends — `class Impl<X, Y> : Swapped<Y, X>()` is legal — so the parent's
         * arguments cannot simply be indexed by the subclass's parameter positions. They are mapped
         * through the supertype reference the subclass declares ([bindTypeParameters]); a parameter
         * the parent says nothing about falls back to its bound.
         */
        private fun resolveSealedTargetType(vType: KSType): KSType {
            val decl = vType.declaration as? KSClassDeclaration ?: return vType
            if (Modifier.SEALED !in decl.modifiers) return vType
            val sub = decl.getSealedSubclasses().firstOrNull() ?: return vType

            val bindings = HashMap<KSTypeParameter, KSType>()
            sub.superTypes
                .map { it.resolve() }
                .firstOrNull { it.declaration == decl }
                ?.let { bindTypeParameters(it, vType, bindings) }
            val arguments = sub.typeParameters.map { vParam ->
                resolver.getTypeArgument(
                    resolver.createKSTypeReferenceFromKSType(bindings[vParam] ?: vParam.boundType()),
                    Variance.INVARIANT,
                )
            }
            return resolveSealedTargetType(sub.asType(arguments))
        }

        /**
         * Registers one type reachable from a mocked interface's signatures as needing a
         * placeholder, unless it's already covered: [builtins], an existing [toMock] entry, or an
         * existing [toFake] entry. An unresolved type parameter is substituted with its first bound,
         * same as [asBoundedType].
         *
         * A nullable reference is registered under its non-nullable form ([KSType.makeNotNullable]),
         * not skipped: `isAny<T>()` and every other `ArgConstraintsBuilder` constraint
         * (`toReturn(constraint, T::class)`) resolves its placeholder through the *erased* `T::class`
         * — never `typeOf<T>()`, which would preserve nullability but fails to compile wherever the
         * same reified `T` might be inferred as a suspend functional type elsewhere ("Suspend
         * functional types are not supported in typeOf", see
         * [KT-47562](https://youtrack.jetbrains.com/projects/KT/issues/KT-47562)) — so there is no
         * way, at that call site, to tell "`T` was `Suit`" apart from "`T` was `Suit?`". A real,
         * non-null placeholder is needed either way, even for a parameter/property/return type that
         * is only ever referenced nullably. Registering under the non-nullable form is also what
         * correctly deduplicates onto the same entry a non-nullable reference to the same class would
         * produce, instead of minting a separate, useless `fakeNulXxx(): Xxx?` one.
         *
         * Once KT-47562 is fixed, `typeOf<T>()` becomes usable in `ArgConstraintsBuilder`'s constraint
         * functions regardless of what `T` might be — including a suspend functional type — and they
         * could resolve a placeholder from it instead of from `T::class`. `typeOf<T>()`, unlike
         * `T::class`, preserves nullability, so a nullable `T` could then be recognized and answered
         * with `null` directly, without needing a real placeholder at all — at which point this
         * workaround (registering a nullable-only-referenced type under its non-nullable form so
         * *some* placeholder exists for it) could be undone, and nullable references could go back to
         * being ignored here, the way they were before this fix.
         *
         * This is unrelated to whether a nullable *value* needs building — [KSType.needsLazyFake],
         * [valueTypeToFake] and [fakeValueOf] still fake a nullable property/parameter/return as a
         * plain `null` immediately, before ever consulting [builtins] or [toFake]; nothing here
         * changes that.
         *
         * The dispatch *key* is always the original type — the one `isAny<T>()`/etc. will actually
         * ask for at runtime (e.g. `SItf::class`, not `SItf.C::class`) — even when [resolveSealedTarget]
         * means the *generated body* ends up constructing a different, concrete permitted subclass;
         * [generateFakeFunction] already does this same redirection internally.
         *
         * `kotlin.Array<T>` gets dedicated handling in [placeholderArrayTypes]: unlike ordinary
         * generics, it isn't erased on the JVM, so a single shared `Array::class` branch can't work
         * for every component type.
         *
         * Function types get dedicated handling in [placeholderFunctionShapes] too — not because
         * `T::class` is any different for them (it erases to `kotlin.Function1`/etc. exactly like
         * any other interface), but because *constructing* a value is: Kotlin/JS forbids a class
         * declaring `: Function1<P1, R>` as a supertype ("Implementing a function interface is
         * prohibited in JavaScript"), so the placeholder for a function-typed target has to be a
         * plain lambda rather than a `MockXxx` class.
         */
        private fun registerFunctionShape(resolved: KSType) {
            val decl = resolved.declaration as? KSClassDeclaration ?: return
            placeholderFunctionShapes[decl] = resolved.isSuspendFunctionType to (resolved.arguments.size - 1)
        }

        private fun seedPlaceholder(type: KSType, origin: String?, path: List<String>) {
            var resolved = type.unwrapAliases().makeNotNullable()
            if (resolved.isAnyFunctionType) {
                registerFunctionShape(resolved)
                return
            }
            if (resolved.declaration is KSTypeParameter) {
                // The bound is a fresh KSType, independent of the makeNotNullable() above — an
                // unbounded `<T>`'s implicit bound is `Any?`, and needs the same treatment, or the
                // identical bug would remain for an unbounded generic parameter.
                resolved = (resolved.declaration as KSTypeParameter).bounds.first().resolve().unwrapAliases().makeNotNullable()
                if (resolved.isAnyFunctionType) {
                    registerFunctionShape(resolved)
                    return
                }
            }
            // Normalizes any further type-parameter mention this type still carries, at any depth —
            // e.g. a mocked interface's own generic member, `fun <T> encode(serializer:
            // KSerializer<T>)` — to its declared parameter's bound, the same way a star projection
            // already is (see withBoundArguments' own doc): [toPlaceholder] is keyed by [KSType], so
            // every seed has to land on a concrete, generatable type before it is registered.
            resolved = resolved.withBoundArguments()
            val decl = resolved.declaration
            if (decl !is KSClassDeclaration) return
            // KSP2's error-type declaration (see KSType.isUnresolved) is a KSClassDeclaration too, so
            // the check above doesn't catch it; skipped here rather than seeded, or it would reach
            // toPlaceholder with no qualifiedName to derive a placeholderXxx() name/package from.
            // providePlaceholder is only ever reached from an argument-constraint fallback for a type
            // that has to be nameable at the *call site* too (T::class) — an unresolved T could never
            // be written there either, so there is no case where skipping the seed here costs a
            // reachable placeholder.
            if (decl.qualifiedName == null) return
            if (decl.qualifiedName?.asString() == "kotlin.Array") {
                // `Array<*>` has no component type to key a component-specific branch on — which is
                // the only reason [placeholderArrayTypes] exists — so leave it to the generic
                // `Array::class -> emptyArray<Any?>()` builtin branch, exactly as any other erased
                // generic is handled.
                if (resolved.arguments.firstOrNull()?.type != null) placeholderArrayTypes += resolved
                return
            }
            if (decl.qualifiedName?.asString() in builtins) return
            if (decl in toMock || resolved in toPlaceholder) return
            // A Fake or a @FakeProvider already covers this exact instantiation — valueTypeToFake
            // returns null in precisely that case (see its own doc) — so nothing needs a Placeholder:
            // the value can be resolved from the Fake instead (see fakeInitializerOf's placeholder
            // mode). Never register a redundant Placeholder for a type another kind already covers.
            if (valueTypeToFake(resolved) == null) return
            toPlaceholder[resolved] = ToProcess().apply { this.origin = origin; implicit = true; this.path = path }
        }

        /**
         * Walks every mocked interface's abstract property types and abstract function *parameter*
         * types — the only shapes `providePlaceholder` is ever asked to answer (see [toPlaceholder]) —
         * and seeds a placeholder for each, via [seedPlaceholder]. Return types are deliberately not
         * walked: inside a definition block, [org.kodein.mock.Mocker.process] throws `CallDefinition`
         * before a mocked member would ever produce one, so nothing needs a value for it.
         *
         * Every [toMock] entry is explicit now — a mock is never discovered transitively — so, unlike
         * the walk this replaces, every mocked interface's non-abstract (default) members are
         * overridden too, and there is no worklist: nothing here can add a new [toMock] entry for this
         * loop to revisit. [expandTransitivePlaceholders] is what continues the walk from here, one
         * step further, into each seeded type's own constructor.
         *
         * Member types are resolved as members of each of [vItf]'s [mockedInstantiations] (falling
         * back to its bounded instantiation when none was recorded — a hand-built [toMock] entry with
         * no real `@Mock`/`@UsesMocks` site behind it), not read off the bare declaration: `isAny<T>()`
         * and every other `ArgConstraintsBuilder` constraint dispatches through the erased, reified
         * `T::class` at its call site, which names the *concrete* type argument (e.g. `NeverTouched`
         * for `Processor<NeverTouched>`), not the declaration's own type-parameter bound — so that is
         * what has to be seeded here, exactly as [implementedMemberTypes] already resolves a faked
         * interface's members against its own instantiation.
         */
        private fun seedPlaceholders() {
            toMock.forEach { (vItf, process) ->
                val overrideAll = vItf.classKind == ClassKind.INTERFACE
                val owner = vItf.simpleName.asString()
                // Already run through withBoundArguments (see mockedInstantiations' own doc), or is
                // asBoundedType()'s own bounded instantiation — either way, nothing further to bind.
                val instantiations = mockedInstantiations[vItf]?.takeIf { it.isNotEmpty() } ?: setOf(vItf.asBoundedType())
                instantiations.forEach { implementedType ->
                    vItf.getAllProperties()
                        .filter { it.isAbstract() }
                        .forEach { vProp ->
                            val vPropType = vProp.asMemberOf(implementedType)
                            seedPlaceholder(vPropType, process.origin, process.path + propertyPathStep(owner, vProp, vPropType))
                        }
                    vItf.getAllFunctions()
                        .filter { it.simpleName.asString() !in IDENTITY_MEMBERS && (overrideAll || it.isAbstract) && it.parameters.isNotEmpty() }
                        .forEach { vFun ->
                            val vFunSig = vFun.asMemberOf(implementedType)
                            // One step for the whole member: which of its parameter types needed the
                            // placeholder is not what a reader is after — where it came from is.
                            val path = process.path + functionPathStep(owner, vFun, vFunSig.parameterTypes, vFunSig.returnType)
                            vFunSig.parameterTypes.filterNotNull().forEach { seedPlaceholder(it, process.origin, path) }
                        }
                }
            }
        }

