/**
 * KSP [SymbolProcessor] that powers MocKMP code generation.
 *
 * Each processing round ([process]) scans the module for MocKMP annotations and emits three kinds
 * of files, in this order:
 *
 * - **Mocks**: for every interface referenced by `@Mock` or `@UsesMocks(...)`, a `MockXxx` class
 *   implementing it, delegating every member to an injected [org.kodein.mock.Mocker]
 *   (see [Round.generateMockClass]).
 * - **Fakes**: for every type referenced by `@Fake`, `@UsesFakes(...)`, or transitively required
 *   as a non-nullable, non-defaulted constructor parameter of another fake, a top-level
 *   `fakeXxx(): Xxx` function that builds a placeholder instance (see [Round.generateFakeFunction]).
 * - **Injectors**: for every class with `@Mock`/`@Fake` annotated properties, a
 *   `Mocker.injectMocks(receiver: Xxx)` function that sets them all (see [Round.generateInjector]).
 *
 * Once at least one mock or fake exists, three small dispatch functions are additionally emitted
 * into [accessorsPackage] — `Mocker.mock(KClass<T>): T`, `fake(KType): T` and
 * `Mocker.injectMocks(Any)` — matching the `expect` declarations generated by the MocKMP Gradle
 * plugin (see `mockmp-gradle-plugin/src/main/resources/mockmp.multi.kt`).
 *
 * The whole pipeline for a single round is implemented by [Round], instantiated fresh on every
 * [process] call so this processor itself carries no state between rounds.
 */
class MocKMPProcessor(
    private val codeGenerator: CodeGenerator,
    private val logger: KSPLogger,
    private val throwErrors: Boolean,
    public: Boolean,
    private val accessorsPackage: String,
    private val multiplatform: Boolean,
) : SymbolProcessor {

    private companion object {
        val mockerTypeName = ClassName("org.kodein.mock", "Mocker")

        // Fully-qualified names of the annotations MocKMP looks for.
        const val ANNOTATION_MOCK = "org.kodein.mock.Mock"
        const val ANNOTATION_FAKE = "org.kodein.mock.Fake"
        const val ANNOTATION_USES_MOCKS = "org.kodein.mock.UsesMocks"
        const val ANNOTATION_USES_FAKES = "org.kodein.mock.UsesFakes"
        const val ANNOTATION_FAKE_PROVIDER = "org.kodein.mock.FakeProvider"

        /**
         * Types for which a literal placeholder can be emitted directly instead of generating (or
         * looking up) a `fakeXxx()` function. Maps a type's qualified name to a KotlinPoet format
         * string and its single format argument (a literal, or a [MemberName] to a factory function).
         */
        val builtins = mapOf(
            "kotlin.Unit" to ("%L" to "Unit"),
            "kotlin.Boolean" to ("%L" to "false"),
            "kotlin.Byte" to ("%L" to "0"),
            "kotlin.Short" to ("%L" to "0"),
            "kotlin.Int" to ("%L" to "0"),
            "kotlin.Long" to ("%L" to "0L"),
            "kotlin.Float" to ("%L" to "0f"),
            "kotlin.Double" to ("%L" to "0.0"),
            "kotlin.String" to ("%L" to "\"\""),
            "kotlin.collections.List" to ("%M()" to MemberName("kotlin.collections", "emptyList")),
            "kotlin.collections.ArrayList" to ("%M()" to MemberName("kotlin.collections", "ArrayList")),
            "java.util.ArrayList" to ("%M()" to MemberName("kotlin.collections", "ArrayList")),
            "kotlin.collections.ArrayDeque" to ("%M()" to MemberName("kotlin.collections", "ArrayDeque")),
            "kotlin.collections.Set" to ("%M()" to MemberName("kotlin.collections", "emptySet")),
            "kotlin.collections.HashSet" to ("%M()" to MemberName("kotlin.collections", "HashSet")),
            "java.util.HashSet" to ("%M()" to MemberName("kotlin.collections", "HashSet")),
            "kotlin.collections.LinkedHashSet" to ("%M()" to MemberName("kotlin.collections", "LinkedHashSet")),
            "java.util.LinkedHashSet" to ("%M()" to MemberName("kotlin.collections", "LinkedHashSet")),
            "kotlin.collections.Map" to ("%M()" to MemberName("kotlin.collections", "emptyMap")),
            "kotlin.collections.HashMap" to ("%M()" to MemberName("kotlin.collections", "HashMap")),
            "java.util.HashMap" to ("%M()" to MemberName("kotlin.collections", "HashMap")),
            "kotlin.collections.LinkedHashMap" to ("%M()" to MemberName("kotlin.collections", "LinkedHashMap")),
            "java.util.LinkedHashMap" to ("%M()" to MemberName("kotlin.collections", "LinkedHashMap")),
            "kotlin.Array" to ("%M()" to MemberName("kotlin", "emptyArray"))
        )
    }

    private val KSType.isAnyFunctionType get() = isFunctionType || isSuspendFunctionType

    /** Follows `typealias` chains to the underlying declaration. */
    private fun KSType.aliasedDeclaration(): KSDeclaration {
        var decl = declaration
        while (decl is KSTypeAlias) decl = decl.type.resolve().declaration
        return decl
    }

    private val visibilityModifier = if (public) KModifier.PUBLIC else KModifier.INTERNAL

    /** Thrown to abort processing of the current round with a location-tagged message. */
    private class Error(message: String, val node: KSNode) : Exception(message)

    override fun process(resolver: Resolver): List<KSAnnotated> =
        try {
            Round(resolver).run()
        } catch (e: Error) {
            logger.error("MocKMP: ${e.message}", e.node)
            if (throwErrors) throw e
            emptyList()
        }

    // region Error reporting

    /** Renders [this] node as a human-readable path, for messages when no [FileLocation] is available. */
    private fun KSNode.asString(): String = when (this) {
        is KSValueParameter -> {
            val nameStr = name?.asString() ?: "?"
            if (parent != null) "${parent!!.asString()}($nameStr)"
            else nameStr
        }
        is KSClassDeclaration -> this.qualifiedName?.asString() ?: this.simpleName.asString()
        else -> (parent?.let { it.asString() + "." } ?: "") + toString()
    }

    /** Fails the current round with [message], pointing [logger] at [node]'s source location when known. */
    private fun error(node: KSNode, message: String): Nothing {
        val prefix = when (val loc = node.location) {
            is FileLocation -> "$node (${loc.filePath}:${loc.lineNumber})"
            is NonExistLocation -> node.asString()
        }
        throw Error("$prefix: $message", node)
    }

    // endregion

    /** The files and annotation sites that referenced a to-be-generated mock or fake, accumulated across annotations. */
    private class ToProcess {
        val files = HashSet<KSFile>()
        val references = HashSet<KSNode>()

        /**
         * True when this entry was discovered implicitly — as a type reachable from a mocked
         * interface's signatures (see [Round.seedImplicitPlaceholders]), not requested directly via
         * `@Mock`/`@Fake`/`@UsesMocks`/`@UsesFakes`. Implicit entries that turn out to be
         * unconstructible get a generated function that throws at runtime instead of aborting the
         * KSP round — nobody asked for that type directly, so failing the whole build over it would
         * be disproportionate. Explicit entries keep failing fast at compile time.
         */
        var implicit: Boolean = false
    }

    // region Naming

    /** The `Outer_Inner_` prefix identifying [this] declaration's chain of enclosing declarations, if any. */
    private fun KSDeclaration.parentPrefix(): String = buildString {
        var pDecl = parentDeclaration
        while (pDecl != null) {
            append(pDecl.simpleName.asString())
            append("_")
            pDecl = pDecl.parentDeclaration
        }
    }

    /** The `foo_bar_` prefix identifying [this] declaration's package, empty for the root package. */
    private fun KSDeclaration.packagePrefix(): String =
        packageName.asString().replace('.', '_').withNonEmptySuffix("_")

    /**
     * A name-safe identifier for the `fakeXxx()` function generated for [this] type: unique per
     * package (`fakedata_Data` vs. `fakefoo_Data`, since both live in the same generated
     * `fakes.kt`), distinct type argument list (`fakeGenDataXkotlin_IntX`, `fakeGenDataXkotlin_StringX`,
     * ...), nesting (`fakeFakeTests_FakeAny` for a nested class `FakeAny` inside `FakeTests`) and
     * nullability.
     */
    private fun KSType.toFunName(): String {
        val prefix = declaration.packagePrefix() + (if (isMarkedNullable) "Nul" else "") + declaration.parentPrefix()
        return prefix +
                if (arguments.isEmpty()) declaration.simpleName.asString()
                else "${declaration.simpleName.asString()}X${
                    arguments.joinToString("_") {
                        if (it.variance == Variance.STAR) "STAR"
                        else it.type!!.resolve().toFunName()
                    }
                }X"
    }

    /** The `MockXxx` class name generated for [this] mocked interface. */
    private fun KSDeclaration.toMockName(): String = "Mock" + parentPrefix() + simpleName.asString()

    /**
     * The package a generated `fakeXxx()` function for [this] declaration is emitted into: its own
     * package, except for Kotlin stdlib packages (which this module cannot write into), redirected
     * under a local `fake.` prefix.
     */
    private fun KSDeclaration.fakePackageName(): String =
        if (packageName.isKotlinStdlib()) "fake." + packageName.asString() else packageName.asString()

    // endregion

    /**
     * Mutable state and generation logic of a single KSP processing round. A fresh instance is
     * created per [process] call, so [MocKMPProcessor] itself carries no state across rounds.
     */
    private inner class Round(private val resolver: Resolver) {

        /** Interfaces referenced by `@Mock`/`@UsesMocks`, with the files/nodes that referenced them. */
        private val toMock = HashMap<KSClassDeclaration, ToProcess>()

        /** Generated `MockXxx` class name, per mocked interface — consumed by [generateMockAccessor]. */
        private val mocks = HashMap<KSClassDeclaration, ClassName>()

        /** Types referenced by `@Fake`/`@UsesFakes`, or required transitively (see [expandTransitiveFakes]). */
        private val toFake = HashMap<KSType, ToProcess>()

        /** Generated `fakeXxx()` function name, per faked type — consumed by [generateFakeAccessor]. */
        private val fakes = HashMap<KSType, MemberName>()

        /** User-supplied `@FakeProvider` functions, keyed by the type they provide a fake for. */
        private val providedFakes = HashMap<KSType, KSFunctionDeclaration>()

        /** Properties annotated `@Mock`/`@Fake`, grouped by enclosing class — consumed by [generateInjector]. */
        private val toInject = HashMap<KSClassDeclaration, ArrayList<Pair<String, KSPropertyDeclaration>>>()

        /**
         * Concrete `Array<T>` types (a known component type) needing a placeholder — kept separate
         * from [toFake]/[toMock] because, unlike ordinary generics, `Array<T>::class` is *not*
         * erased on the JVM: each component type is a genuinely distinct runtime class, so
         * `Array<String>::class` and `Array<Int>::class` can't share one `when` branch the way
         * `List<String>::class == List<Int>::class` can. Consumed by [generatePlaceholderAccessor].
         */
        private val placeholderArrayTypes = LinkedHashSet<KSType>()

        /**
         * Function-typed shapes found while seeding implicit placeholders, keyed by the exact
         * declaration KSP resolves the type to (`kotlin.Function1`, `kotlin.coroutines.SuspendFunction1`,
         * etc. — deliberately *not* hand-built from an arity count: the JVM backend's CPS transform
         * means a suspend type's *reified* runtime class doesn't necessarily follow the naming
         * scheme its own frontend declaration suggests, so reusing KSP's own resolution is the only
         * reliable way to get a matching `T::class`). Mapped to (isSuspend, parameterCount), needed
         * to build the placeholder lambda's shape. Kept separate from [toMock] — a generated class
         * can't `: Function1<P1, R>` on Kotlin/JS ("Implementing a function interface is prohibited
         * in JavaScript"), so a plain lambda is used instead — consumed by [generatePlaceholderAccessor].
         */
        private val placeholderFunctionShapes = LinkedHashMap<KSClassDeclaration, Pair<Boolean, Int>>()

        /** Runs the full pipeline for this round: collect, expand, then generate every kind of file. */
        fun run(): List<KSAnnotated> {
            collectAnnotatedSymbols()
            collectFakeProviders()
            seedImplicitPlaceholders()
            expandTransitiveFakes()

            toMock.forEach { (vItf, process) -> generateMockClass(vItf, process) }
            toFake.forEach { (vType, process) -> generateFakeFunction(vType, process) }
            toInject.forEach { (vCls, _) -> generateInjector(vCls) }

            if (mocks.isNotEmpty() || fakes.isNotEmpty()) {
                generateMockAccessor()
                generateFakeAccessor()
                generateInjectorAccessor()
                generatePlaceholderAccessor()
            }

            return emptyList()
        }

        // region Phase 1: collect annotated symbols

        /**
         * Registers [type] as needing a `MockXxx` class, or fails if it isn't an interface or an
         * abstract class. [implicit] marks entries discovered by [seedImplicitPlaceholders] rather
         * than requested directly.
         */
        private fun addMock(type: KSType, files: Iterable<KSFile>, node: KSNode, implicit: Boolean = false) {
            if (type.isFunctionType) return
            val decl = type.declaration
            val isMockable = decl is KSClassDeclaration &&
                    (decl.classKind == ClassKind.INTERFACE || (decl.classKind == ClassKind.CLASS && Modifier.ABSTRACT in decl.modifiers))
            if (!isMockable) error(node, "Cannot generate mock for non interface $decl")
            toMock.getOrPut(decl) { ToProcess().apply { this.implicit = implicit } }.let {
                it.files.addAll(files)
                it.references.add(node)
            }
        }

        /**
         * Registers [type] as needing a `fakeXxx()` function, or fails if it isn't a fakeable
         * class/enum. Sealed classes/interfaces are allowed through — [generateFakeFunction]
         * resolves them to a constructible permitted subclass at generation time. [implicit] marks
         * entries discovered by [seedImplicitPlaceholders] rather than requested directly.
         */
        private fun addFake(type: KSType, files: Iterable<KSFile>, node: KSNode, implicit: Boolean = false) {
            val decl = type.declaration

            if (decl !is KSClassDeclaration) {
                error(node, "Cannot generate fake for ${decl.javaClass.simpleName} ${decl.qualifiedName?.asString() ?: decl.simpleName.asString()}")
            }
            val isSealed = Modifier.SEALED in decl.modifiers
            if (!isSealed && (decl.isAbstract() || decl.classKind !in arrayOf(ClassKind.CLASS, ClassKind.ENUM_CLASS))) {
                error(node, "Cannot generate fake for ${if (decl.isAbstract()) "abstract " else ""}${decl.classKind.type} ${decl.qualifiedName?.asString() ?: decl.simpleName.asString()}")
            }
            toFake.getOrPut(type) { ToProcess().apply { this.implicit = implicit } }.let {
                it.files.addAll(files)
                it.references.add(node)
            }
        }

        /** Finds every property annotated [annotationName] (or its setter), registers its class for injection, and [add]s its type. */
        private fun lookUpFields(annotationName: String, add: (KSType, Iterable<KSFile>, KSNode) -> Unit) {
            val symbols = resolver.getSymbolsWithAnnotation(annotationName)
            symbols.forEach { symbol ->
                val prop = when (symbol) {
                    is KSPropertySetter -> symbol.receiver
                    is KSPropertyDeclaration -> {
                        if (!symbol.isMutable) error(symbol, "$symbol is immutable but is annotated with @${annotationName.split(".").last()}")
                        symbol
                    }
                    else -> error(symbol, "$symbol is not a property nor a property setter but is annotated with @${annotationName.split(".").last()} (is ${symbol::class.simpleName})")
                }
                val cls = prop.parentDeclaration as? KSClassDeclaration ?: error(symbol, "Cannot generate injector for $prop as it is not inside a class")
                toInject.getOrPut(cls) { ArrayList() }.add(annotationName to prop)
                add(prop.type.resolve(), listOf(cls.containingFile!!), symbol)
            }
        }

        /** Finds every declaration annotated `@UsesMocks(...)`/`@UsesFakes(...)` and [add]s each type listed in [annotationName]'s array argument. */
        private fun lookUpUses(annotationName: String, add: (KSType, Iterable<KSFile>, KSNode) -> Unit) {
            val uses = resolver.getSymbolsWithAnnotation(annotationName)
            uses.forEach { use ->
                val anno = use.annotations.first { it.annotationType.resolve().declaration.qualifiedName!!.asString() == annotationName }
                (anno.arguments.first().value as List<*>).forEach {
                    add((it as KSType), listOf(use.containingFile!!), use)
                }
            }
        }

        /** Populates [toMock], [toFake] and [toInject] from `@Mock`, `@Fake`, `@UsesMocks` and `@UsesFakes`. */
        private fun collectAnnotatedSymbols() {
            lookUpFields(ANNOTATION_MOCK, ::addMock)
            lookUpFields(ANNOTATION_FAKE, ::addFake)
            lookUpUses(ANNOTATION_USES_MOCKS, ::addMock)
            lookUpUses(ANNOTATION_USES_FAKES, ::addFake)
        }

        /**
         * Populates [providedFakes] from `@FakeProvider` top-level functions, and removes their
         * return type from [toFake] — a user-supplied provider makes generation unnecessary.
         */
        private fun collectFakeProviders() {
            resolver.getSymbolsWithAnnotation(ANNOTATION_FAKE_PROVIDER).forEach {
                if (it !is KSFunctionDeclaration || it.parent !is KSFile) error(it, "Only top-level functions can be annotated with @FakeProvider")
                val type = it.returnType!!.resolve()
                val typeDeclaration = type.declaration
                if (typeDeclaration !is KSClassDeclaration) error(it, "@FakeProvider functions must return class types.")
                if (type in providedFakes) error(it, "Only one @FakeProvider function must exist for this type (other is ${providedFakes[type]!!.asString()}).")
                toFake.remove(type)
                providedFakes[type] = it
            }
        }

        // endregion

        // region Phase 1.5: implicit placeholders

        /**
         * A representative [KSType] for [this] declaration, substituting each type parameter with
         * its first bound (e.g. `T : Any` becomes `Any`) — the same "good enough" stand-in
         * [generateMockAccessor] already uses when the concrete type argument is unknown.
         */
        private fun KSClassDeclaration.asBoundedType(): KSType =
            asType(typeParameters.map { resolver.getTypeArgument(it.bounds.first(), Variance.INVARIANT) })

        /** The stand-in type for [this] type parameter when no argument is known: its first bound, or `Any?`. */
        private fun KSTypeParameter.boundType(): KSType =
            bounds.firstOrNull()?.resolve() ?: resolver.builtIns.anyType.makeNullable()

        /**
         * If [decl] is sealed (class or interface), returns its first permitted subclass, resolved
         * recursively through nested sealed hierarchies. Returns [decl] unchanged when it isn't
         * sealed, or when a sealed hierarchy has no permitted subclasses (construction then fails
         * naturally later, with a reasonable "no public constructor" message).
         *
         * [resolveSealedTargetType] is the type-level counterpart, and must keep picking the same
         * subclass as this one.
         */
        private fun resolveSealedTarget(decl: KSClassDeclaration): KSClassDeclaration {
            if (Modifier.SEALED !in decl.modifiers) return decl
            val first = decl.getSealedSubclasses().firstOrNull() ?: return decl
            return resolveSealedTarget(first)
        }

        /**
         * Binds the type parameters [declared] is written in terms of to the matching arguments of
         * [actual], recursively — unifying `Swapped<Y, X>` against `Swapped<String, Int>` binds
         * `Y` to `String` and `X` to `Int`.
         */
        private fun bindTypeParameters(declared: KSType, actual: KSType, into: MutableMap<KSTypeParameter, KSType>) {
            val decl = declared.declaration
            if (decl is KSTypeParameter) {
                into[decl] = actual
                return
            }
            declared.arguments.forEachIndexed { index, argument ->
                val declaredArgument = argument.type?.resolve() ?: return@forEachIndexed
                val actualArgument = actual.arguments.getOrNull(index)?.type?.resolve() ?: return@forEachIndexed
                bindTypeParameters(declaredArgument, actualArgument, into)
            }
        }

        /**
         * [resolveSealedTarget] at the type level: the permitted subclass that will actually be
         * constructed for [vType], expressed with *its own* type arguments.
         *
         * A subclass does not have to declare the same type parameters, in the same order, as the
         * sealed parent it extends — `class Impl<X, Y> : Swapped<Y, X>()` is legal — so the parent's
         * arguments cannot simply be indexed by the subclass's parameter positions. They are mapped
         * through the supertype reference the subclass declares ([bindTypeParameters]); a parameter
         * the parent says nothing about falls back to its bound.
         */
        private fun resolveSealedTargetType(vType: KSType): KSType {
            val decl = vType.declaration as? KSClassDeclaration ?: return vType
            if (Modifier.SEALED !in decl.modifiers) return vType
            val sub = decl.getSealedSubclasses().firstOrNull() ?: return vType

            val bindings = HashMap<KSTypeParameter, KSType>()
            sub.superTypes
                .map { it.resolve() }
                .firstOrNull { it.declaration == decl }
                ?.let { bindTypeParameters(it, vType, bindings) }
            val arguments = sub.typeParameters.map { vParam ->
                resolver.getTypeArgument(
                    resolver.createKSTypeReferenceFromKSType(bindings[vParam] ?: vParam.boundType()),
                    Variance.INVARIANT,
                )
            }
            return resolveSealedTargetType(sub.asType(arguments))
        }

        /** Follows type alias declarations (e.g. `typealias BarCB = (String) -> Int`) down to the real type they expand to. */
        private fun KSType.unwrapAliases(): KSType {
            var t = this
            while (t.declaration is KSTypeAlias) t = (t.declaration as KSTypeAlias).type.resolve()
            return t
        }

        /**
         * Registers one type reachable from a mocked interface's signatures as needing a
         * placeholder, unless it's already covered: [builtins], an existing [toMock] entry, or an
         * existing [toFake] entry. Nullable types need no placeholder (`null` is a valid one). An
         * unresolved type parameter is substituted with its first bound, same as [asBoundedType].
         *
         * The dispatch *key* is always the original type — the one `isAny<T>()`/etc. will actually
         * ask for at runtime (e.g. `SItf::class`, not `SItf.C::class`) — even when [resolveSealedTarget]
         * means the *generated body* ends up constructing a different, concrete permitted subclass;
         * [generateFakeFunction] already does this same redirection internally.
         *
         * `kotlin.Array<T>` gets dedicated handling in [placeholderArrayTypes]: unlike ordinary
         * generics, it isn't erased on the JVM, so a single shared `Array::class` branch can't work
         * for every component type.
         *
         * Function types get dedicated handling in [placeholderFunctionShapes] too — not because
         * `T::class` is any different for them (it erases to `kotlin.Function1`/etc. exactly like
         * any other interface), but because *constructing* a value is: Kotlin/JS forbids a class
         * declaring `: Function1<P1, R>` as a supertype ("Implementing a function interface is
         * prohibited in JavaScript"), so the placeholder for a function-typed target has to be a
         * plain lambda rather than a `MockXxx` class.
         */
        private fun registerFunctionShape(resolved: KSType) {
            val decl = resolved.declaration as? KSClassDeclaration ?: return
            placeholderFunctionShapes[decl] = resolved.isSuspendFunctionType to (resolved.arguments.size - 1)
        }

        private fun seedImplicitPlaceholder(type: KSType) {
            if (type.nullability != Nullability.NOT_NULL) return
            var resolved = type.unwrapAliases()
            if (resolved.isAnyFunctionType) {
                registerFunctionShape(resolved)
                return
            }
            if (resolved.declaration is KSTypeParameter) {
                resolved = (resolved.declaration as KSTypeParameter).bounds.first().resolve().unwrapAliases()
                if (resolved.isAnyFunctionType) {
                    registerFunctionShape(resolved)
                    return
                }
            }
            val decl = resolved.declaration
            if (decl !is KSClassDeclaration) return
            if (decl.qualifiedName?.asString() == "kotlin.Array") {
                placeholderArrayTypes += resolved
                return
            }
            if (decl.qualifiedName?.asString() in builtins) return
            if (decl in toMock || resolved in toFake) return
            val target = resolveSealedTarget(decl)
            when {
                target != decl -> toFake[resolved] = ToProcess().apply { implicit = true }
                decl.classKind == ClassKind.INTERFACE || (decl.classKind == ClassKind.CLASS && Modifier.ABSTRACT in decl.modifiers) ->
                    toMock[decl] = ToProcess().apply { implicit = true }
                decl.classKind == ClassKind.CLASS || decl.classKind == ClassKind.ENUM_CLASS ->
                    toFake[resolved] = ToProcess().apply { implicit = true }
                else -> {}
            }
        }

        /**
         * Walks every interface/abstract class already in [toMock] and seeds a placeholder for
         * every parameter, return, and property type reachable from its members — the set of types
         * `isAny()`/`isEqual()`/etc. may need to return a value for. For an *implicit* entry, only
         * abstract members are walked, mirroring [generateMockClass]'s decision to only override
         * abstract members for such a target — walking (and then generating an override for) a JDK
         * default method like `Iterable.forEach(Consumer)` has repeatedly proven to be a source of
         * variance conflicts and out-of-bounds package restrictions for no benefit, since a
         * placeholder is never meant to be genuinely invoked anyway. Runs as a worklist since a
         * newly-seeded abstract class or interface may itself reference further types.
         */
        private fun seedImplicitPlaceholders() {
            val toExplore = ArrayDeque(toMock.keys)
            while (toExplore.isNotEmpty()) {
                val vItf = toExplore.removeFirst()
                val overrideAll = vItf.classKind == ClassKind.INTERFACE && !toMock.getValue(vItf).implicit
                val before = HashSet(toMock.keys)
                vItf.getAllProperties()
                    .filter { it.isAbstract() }
                    .forEach { vProp -> seedImplicitPlaceholder(vProp.type.resolve()) }
                vItf.getAllFunctions()
                    .filter { if (overrideAll) it.simpleName.asString() !in listOf("equals", "hashCode") else it.isAbstract }
                    .forEach { vFun ->
                        vFun.parameters.forEach { seedImplicitPlaceholder(it.type.resolve()) }
                        vFun.returnType?.let { seedImplicitPlaceholder(it.resolve()) }
                    }
                toMock.keys.forEach { if (it !in before) toExplore.add(it) }
            }
        }

        // endregion

        // region Phase 2: transitive fakes

        /**
         * [type] with every reference to one of [vCls]'s type parameters replaced by the matching
         * type argument of [vType] — `GenData<T>` becomes `GenData<String>` when [vType] is
         * `Wrap<String>` — or `null` when one of them belongs to an enclosing declaration rather
         * than to [vCls], which the arguments of [vType] say nothing about.
         *
         * When [vType] projects a type parameter with a star — which is all a `KClass` reference can
         * express, so it is what every `@UsesFakes(Generic::class)` produces — the parameter's first
         * bound stands in for it, the same "good enough" substitute [asBoundedType] uses. An
         * undeclared bound is `Any?`, which is why `NullGenData<T>(val content: T)` fakes its content
         * as `null` while `NonNullGenData<T : Any>` fakes it as an `Any` instance.
         *
         * Substitution is recursive: a type parameter can be nested at any depth (`GenData<GenData<T>>`,
         * `() -> GenData<T>`), and only substituting a *bare* type parameter would leave the rest
         * unresolved — with no `fakeGenDataXTX()` function to call for it.
         *
         * Returns [type] itself when nothing was substituted: [toFake], [fakes] and [providedFakes]
         * are keyed by [KSType], so a rebuilt-but-equivalent instance must never be introduced needlessly.
         */
        private fun substituteTypeParameters(type: KSType, vCls: KSClassDeclaration, vType: KSType): KSType? {
            val decl = type.declaration
            if (decl is KSTypeParameter) {
                val index = vCls.typeParameters.indexOf(decl)
                if (index < 0) return null
                val resolved = vType.arguments.getOrNull(index)?.type?.resolve() ?: decl.boundType()
                // `T?` substitutes to `String?`, not to `String`: dropping the nullability would make
                // constructorParamTypeToFake (which skips nullable parameters) and resolveConstructorArgs
                // (which emits `null` for them) disagree on whether a fake is needed at all.
                return if (type.isMarkedNullable) resolved.makeNullable() else resolved
            }
            if (type.arguments.isEmpty()) return type

            var substituted = false
            val arguments = type.arguments.map { argument ->
                val argumentType = argument.type?.resolve() ?: return@map argument // A star projection has nothing to substitute.
                val resolved = substituteTypeParameters(argumentType, vCls, vType) ?: return null
                if (resolved == argumentType) return@map argument
                substituted = true
                resolver.getTypeArgument(resolver.createKSTypeReferenceFromKSType(resolved), argument.variance)
            }
            return if (substituted) type.replace(arguments) else type
        }

        /**
         * Resolves the type a fake is needed for, for constructor [param] of fake class [vCls]
         * (whose fake is being generated for [vType]) — or `null` if [param] needs no fake: it has
         * a default value, is nullable, resolves to a [builtins] type, or already has one
         * ([providedFakes] or [toFake]).
         */
        private fun constructorParamTypeToFake(vCls: KSClassDeclaration, vType: KSType, param: KSValueParameter, process: ToProcess): KSType? {
            if (param.hasDefault) return null
            // Nullability is tested *after* substitution, as [resolveConstructorArgs] does: a type
            // parameter can substitute to a nullable type, and the two must agree on which
            // parameters get a fake and which are simply set to `null`.
            var paramType = substituteTypeParameters(param.type.resolve(), vCls, vType)
                ?: error(param, "Could not resolve generic parameter $param (${process.references.firstOrNull()?.location})")
            if (paramType.nullability != Nullability.NOT_NULL) return null

            if (paramType.isAnyFunctionType) {
                paramType = paramType.arguments.last().type!!.resolve()
            }
            return paramType.takeIf { it.aliasedDeclaration().qualifiedName?.asString() !in builtins && it !in providedFakes && it !in toFake }
        }

        /**
         * Breadth-first expansion of [toFake]: a fake class may itself require fakes for its own
         * constructor parameter types (a `data class Foo(val bar: Bar)` needs `fakeBar()` too), so
         * this walks the constructor graph and adds any parameter type not already covered. Also
         * seeds from [toMock]'s abstract-class entries (see [addMock]) — their superclass
         * constructor call (built by [addSuperclassConstructorArgs]) needs the same treatment.
         * Discovered types inherit their parent's [ToProcess.implicit] flag: if the whole chain
         * exists only because of an implicit placeholder need, nobody asked for any of it directly,
         * so none of it should be able to abort the KSP round.
         */
        private fun expandTransitiveFakes() {
            val abstractMockSeeds = toMock.entries
                .filter { (decl, _) -> Modifier.ABSTRACT in decl.modifiers }
                .map { (decl, process) -> decl.asBoundedType() to process }
            val toExplore = ArrayDeque(toFake.map { it.toPair() } + abstractMockSeeds)
            while (toExplore.isNotEmpty()) {
                val (type, process) = toExplore.removeFirst()
                // The constructor that will be called is the sealed target's, not the sealed parent's
                // (which isn't even public) — the two phases must walk the same one.
                val targetType = resolveSealedTargetType(type)
                val cls = targetType.declaration as KSClassDeclaration
                cls.firstPublicConstructor()?.parameters?.forEach { param ->
                    val paramTypeToFake = constructorParamTypeToFake(cls, targetType, param, process) ?: return@forEach
                    addFake(paramTypeToFake, process.files, param, implicit = process.implicit)
                    toExplore.add(paramTypeToFake to process)
                }
            }
        }

